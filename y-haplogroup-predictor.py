class Style:
    def __init__(self, enabled):
        self.enabled = enabled

    def __call__(self, text, code):
        return f"\033[{code}m{text}\033[0m" if self.enabled else text

    def bold(self, text):
        return self(text, "1")

    def dim(self, text):
        return self(text, "2")

    def support(self, text, p):
        return self(text, "32" if p >= 0.99 else "33" if p >= 0.9 else "31")


class Sample:
    def __init__(self, path):
        self.path = path
        self.label = os.path.basename(path)
        self.vendor = None
        self.kind = "table"
        self.build_hint = None
        self.vcf_sample = None
        self.by_pos = {}
        self.by_id = {}
        self.conflicting_pos = set()
        self.y_rows = 0
        self.y_called = 0
        self.y_nocall = 0
        self.y_het = 0
        self.y_indel = 0
        self.x_called = 0
        self.x_het = 0

    def add(self, chrom, pos, snp_id, call, status):
        if chrom == "X":
            if pos and X_NON_PAR[0] <= pos <= X_NON_PAR[1] and status in ("call", "het"):
                self.x_called += 1
                self.x_het += status == "het"
            return
        if chrom != "Y":
            return
        self.y_rows += 1
        if status != "call":
            if status == "het":
                self.y_het += 1
            elif status == "indel":
                self.y_indel += 1
            else:
                self.y_nocall += 1
            return
        self.y_called += 1
        if pos:
            if pos in self.conflicting_pos:
                pass
            elif pos in self.by_pos and self.by_pos[pos] != call:
                del self.by_pos[pos]
                self.conflicting_pos.add(pos)
            else:
                self.by_pos[pos] = call
        if snp_id and snp_id != ".":
            self.by_id[snp_id] = call


def open_text(path):
    with open(path, "rb") as f:
        magic = f.read(4)
    if magic[:2] == b"\x1f\x8b":
        raw = gzip.open(path, "rb")
    elif magic[:3] == b"BZh":
        raw = bz2.open(path, "rb")
    elif magic == b"PK\x03\x04":
        archive = zipfile.ZipFile(path)
        members = [m for m in archive.infolist()
                   if not m.is_dir() and not os.path.basename(m.filename).startswith(".")
                   and "__MACOSX" not in m.filename]
        if not members:
            raise ValueError("zip archive contains no files")
        member = max(members, key=lambda m: m.file_size)
        with archive.open(member) as probe:
            inner = probe.read(2)
        raw = archive.open(member)
        if inner == b"\x1f\x8b":
            raw = gzip.GzipFile(fileobj=raw)
    else:
        raw = open(path, "rb")
    head = raw.peek(2)[:2] if hasattr(raw, "peek") else b""
    encoding = "utf-16" if head in (b"\xff\xfe", b"\xfe\xff") else "utf-8-sig"
    return io.TextIOWrapper(raw, encoding=encoding, errors="replace", newline=None)


def norm_chrom(text):
    c = text.strip().strip('"').upper()
    if c.startswith("CHR"):
        c = c[3:]
    return CHROM_ALIASES.get(c, c)


def parse_genotype(text):
    g = text.strip().upper()
    for ch in " /|;:\"'":
        g = g.replace(ch, "")
    if g in NO_CALL:
        return None, "nocall"
    if len(g) == 1:
        if g in BASES:
            return g, "call"
        return None, "indel" if g in "ID" else "nocall"
    if len(g) == 2:
        a, b = g
        if a in BASES and b in BASES:
            return (a, "call") if a == b else (None, "het")
        if a in BASES and b in "0-N":
            return a, "call"
        if b in BASES and a in "0-N":
            return b, "call"
        if a in "ID" and b in "ID":
            return None, "indel"
    return None, "nocall"


def split_fields(line):
    if "\t" in line:
        return [f.strip().strip('"').strip() for f in line.split("\t")]
    if "," in line:
        return [f.strip() for f in line.replace('"', "").split(",")]
    return line.split()


def map_columns(fields):
    cols = {}
    for i, name in enumerate(f.lower().lstrip("#").replace("_", " ").strip() for f in fields):
        if name in ID_COLUMNS:
            cols.setdefault("id", i)
        elif name in CHROM_COLUMNS:
            cols.setdefault("chrom", i)
        elif name in POS_COLUMNS or name.startswith("position"):
            cols.setdefault("pos", i)
        elif name in GENOTYPE_COLUMNS:
            cols.setdefault("gt", i)
        elif name.replace(" ", "").startswith("allele1"):
            cols.setdefault("a1", i)
        elif name.replace(" ", "").startswith("allele2"):
            cols.setdefault("a2", i)
    if "chrom" in cols and "pos" in cols and ("gt" in cols or "a1" in cols):
        return cols
    return None


def guess_columns(fields):
    if len(fields) >= 4 and fields[2].isdigit():
        if len(fields) == 4:
            return {"id": 0, "chrom": 1, "pos": 2, "gt": 3}
        return {"id": 0, "chrom": 1, "pos": 2, "a1": 3, "a2": 4}
    return None


def note_header(sample, text):
    low = text.lower()
    if sample.vendor is None:
        for key, vendor in VENDOR_HINTS:
            if key in low:
                sample.vendor = vendor
                break
    if sample.build_hint is None:
        for key, build in BUILD_HINTS:
            if key in low:
                sample.build_hint = build
                break


def vcf_genotype(ref, alts, gt):
    alleles = [ref] + alts
    parts = gt.replace("|", "/").split("/")
    if any(p in (".", "") for p in parts):
        return None, "nocall"
    try:
        called = {alleles[int(p)] for p in parts}
    except (ValueError, IndexError):
        return None, "nocall"
    if len(called) != 1:
        return None, "het"
    allele = called.pop()
    if allele in BASES:
        return allele, "call"
    if allele.startswith("<") or allele == "*":
        return None, "nocall"
    return None, "indel"


def read_sample(path, vcf_sample=None):
    sample = Sample(path)
    cols = None
    vcf_index = None
    with open_text(path) as f:
        for raw in f:
            line = raw.rstrip("\r\n")
            if not line.strip():
                continue
            if sample.kind == "table" and cols is None and (line.startswith("##fileformat=VCF") or line.startswith("#CHROM")):
                sample.kind = "vcf"
            if sample.kind == "vcf":
                if line.startswith("##"):
                    note_header(sample, line)
                    low = line.lower()
                    if low.startswith("##contig=") and ("id=y," in low or "id=chry," in low):
                        for part in low.split(","):
                            if part.startswith("length="):
                                length = int("".join(ch for ch in part[7:] if ch.isdigit()) or 0)
                                sample.build_hint = CONTIG_Y_LENGTH.get(length, sample.build_hint)
                    continue
                fields = line.split("\t")
                if line.startswith("#CHROM"):
                    names = fields[9:]
                    if not names:
                        raise ValueError("VCF has no sample columns")
                    if vcf_sample is None:
                        vcf_index = 9
                    elif vcf_sample in names:
                        vcf_index = 9 + names.index(vcf_sample)
                    else:
                        raise ValueError(f"sample {vcf_sample} not in VCF ({', '.join(names[:5])}...)")
                    sample.vcf_sample = fields[vcf_index]
                    continue
                if vcf_index is None or len(fields) <= vcf_index:
                    continue
                chrom = norm_chrom(fields[0])
                if chrom not in ("X", "Y"):
                    continue
                if fields[6] not in ("PASS", ".", "", "RefCall"):
                    continue
                ref = fields[3].upper()
                alts = fields[4].upper().split(",")
                fmt = fields[8].split(":")
                if "GT" not in fmt:
                    continue
                values = fields[vcf_index].split(":")
                gt_i = fmt.index("GT")
                gt = values[gt_i] if gt_i < len(values) else "."
                if len(ref) != 1:
                    call, status = None, "indel"
                else:
                    call, status = vcf_genotype(ref, alts, gt)
                pos = int(fields[1]) if fields[1].isdigit() else 0
                sample.add(chrom, pos, fields[2], call, status)
                continue

            if line.startswith("#") or cols is None:
                fields = split_fields(line.lstrip("#").strip())
                header = map_columns(fields)
                if header:
                    cols = header
                    continue
                if line.startswith("#") or line.startswith("["):
                    note_header(sample, line)
                    continue
                if cols is None:
                    cols = guess_columns(fields)
                    if cols is None:
                        note_header(sample, line)
                        continue
            fields = split_fields(line)
            try:
                chrom = norm_chrom(fields[cols["chrom"]])
                if chrom not in ("X", "Y"):
                    continue
                pos_text = fields[cols["pos"]]
                pos = int(pos_text) if pos_text.isdigit() else 0
                snp_id = fields[cols["id"]] if "id" in cols else ""
                if "gt" in cols:
                    call, status = parse_genotype(fields[cols["gt"]])
                else:
                    a2 = fields[cols["a2"]] if "a2" in cols and cols["a2"] < len(fields) else ""
                    call, status = parse_genotype(fields[cols["a1"]] + a2)
            except IndexError:
                continue
            sample.add(chrom, pos, snp_id, call, status)
    return sample


class Marker:
    __slots__ = ("node", "pos37", "pos38", "anc", "der", "names", "rsids", "recurrent")

    def __init__(self, node, pos37, pos38, anc, der, names, rsids, recurrent):
        self.node = node
        self.pos37 = pos37
        self.pos38 = pos38
        self.anc = anc
        self.der = der
        self.names = names
        self.rsids = rsids
        self.recurrent = recurrent

    @property
    def name(self):
        return self.names.split("/", 1)[0]


class TreeDB:
    def __init__(self, path, want_pos=frozenset(), want_ids=frozenset(), want_names=frozenset()):
        if not os.path.exists(path):
            raise FileNotFoundError(f"tree database not found: {path} (run build-ydb.py or pass --db)")
        self.file = path
        self.meta = {}
        self.parent = []
        self.ids = []
        self.formed = []
        self.tmrca = []
        self.markers = []
        with gzip.open(path, "rt", encoding="utf-8") as f:
            for line in f:
                if line[0] == "#":
                    parts = line[1:].rstrip("\n").split("\t")
                    self.meta[parts[0]] = parts[1:]
                    continue
                if line[0] == "N":
                    _, idx, parent, nid, formed, tmrca = line.rstrip("\n").split("\t")
                    self.parent.append(int(parent))
                    self.ids.append(nid)
                    self.formed.append(int(formed))
                    self.tmrca.append(int(tmrca))
                    continue
                node, p37, off, alleles, names, rsids, flags = line.rstrip("\n").split("\t")
                pos37 = int(p37)
                pos38 = pos37 + int(off) if off else 0
                hit = pos37 in want_pos or (pos38 and pos38 in want_pos)
                if not hit and rsids and want_ids:
                    hit = any(r in want_ids for r in rsids.split(","))
                if not hit and want_names:
                    hit = any(n.upper() in want_names for n in names.split("/"))
                if hit:
                    self.markers.append(Marker(int(node), pos37, pos38, alleles[0], alleles[1], names,
                                               rsids.split(",") if rsids else [], "u" in flags))
        if self.meta.get("ydb", [""])[0] != "3":
            raise ValueError(f"{path} is not a version 3 tree database; rebuild it with build-ydb.py")
        per_site = {}
        for m in self.markers:
            per_site[m.pos37] = per_site.get(m.pos37, 0) + 1
        for m in self.markers:
            m.recurrent = m.recurrent or per_site[m.pos37] > 1
        self.n = len(self.parent)
        self.depth = [0] * self.n
        for i in range(1, self.n):
            self.depth[i] = self.depth[self.parent[i]] + 1
        self.size = [1] * self.n
        for i in range(self.n - 1, 0, -1):
            self.size[self.parent[i]] += self.size[i]
        self._index = None
        self._children = None

    @property
    def version(self):
        return " ".join(self.meta.get("tree", ["unknown"])[:1])

    def index_of(self, node_id):
        if self._index is None:
            self._index = {nid.upper(): i for i, nid in enumerate(self.ids)}
        return self._index.get(node_id.upper())

    def children(self, node):
        if self._children is None:
            self._children = [[] for _ in range(self.n)]
            for i in range(1, self.n):
                self._children[self.parent[i]].append(i)
        return self._children[node]

    def path(self, node):
        out = []
        while node >= 0:
            out.append(node)
            node = self.parent[node]
        return out[::-1]

    def contains(self, clade, node):
        return clade <= node < clade + self.size[clade]

    def major(self, node):
        for i in reversed(self.path(node)):
            nid = self.ids[i]
            if "-" not in nid or nid == "A0-T":
                return nid
        return self.ids[node]


def log_odds(error_rate):
    return math.log((1.0 - error_rate) / error_rate)


def match_sample(sample, db, build, allow_complement):
    candidates = {}
    for mode in ("GRCh37", "GRCh38", "rsID"):
        if build not in ("auto", mode):
            continue
        hits = []
        for m in db.markers:
            if mode == "GRCh37":
                call = sample.by_pos.get(m.pos37)
            elif mode == "GRCh38":
                call = sample.by_pos.get(m.pos38) if m.pos38 else None
            else:
                call = next((sample.by_id[r] for r in m.rsids if r in sample.by_id), None)
            if call is not None:
                hits.append((m, call))
        informative = len({m.pos37 for m, c in hits if c in (m.anc, m.der)})
        candidates[mode] = (informative, hits)
    if not candidates:
        return "none", [], 0
    hint = {37: "GRCh37", 38: "GRCh38", 36: "rsID"}.get(sample.build_hint, "GRCh37")
    order = sorted(candidates, key=lambda k: (candidates[k][0], k == hint), reverse=True)
    mode = order[0]
    hits = candidates[mode][1]
    direct = flipped = 0
    for m, c in hits:
        if c in (m.anc, m.der):
            direct += 1
        elif COMPLEMENT.get(c) in (m.anc, m.der) and {m.anc, m.der} not in PALINDROMIC:
            flipped += 1
    use_complement = allow_complement == "yes" or (
        allow_complement == "auto" and flipped >= 5 and flipped >= 0.2 * (direct + flipped))
    return mode, hits, use_complement


def classify(hits, use_complement, w_unique, w_recurrent, exclude):
    obs = []
    other = flipped = ambiguous = 0
    for m, call in hits:
        if exclude and any(n.upper() in exclude for n in m.names.split("/")):
            continue
        allele = call
        if use_complement and {m.anc, m.der} in PALINDROMIC:
            ambiguous += 1
            continue
        if call not in (m.anc, m.der):
            if use_complement and COMPLEMENT.get(call) in (m.anc, m.der):
                allele = COMPLEMENT[call]
                flipped += 1
            else:
                other += 1
                continue
        obs.append((m, call, allele == m.der, w_recurrent if m.recurrent else w_unique))
    return obs, other, flipped, ambiguous


def place(db, obs, min_support):
    n = db.n
    parent = db.parent
    score = [0.0] * n
    for m, call, derived, w in obs:
        score[m.node] += w if derived else -w
    s = score[:]
    for i in range(1, n):
        s[i] += s[parent[i]]
    best_in = s[:]
    for i in range(n - 1, 0, -1):
        if best_in[i] > best_in[parent[i]]:
            best_in[parent[i]] = best_in[i]
    neg = float("-inf")
    prefix = [neg] * (n + 1)
    for i in range(n):
        prefix[i + 1] = s[i] if s[i] > prefix[i] else prefix[i]
    suffix = [neg] * (n + 1)
    for i in range(n - 1, -1, -1):
        suffix[i] = s[i] if s[i] > suffix[i + 1] else suffix[i + 1]

    def best_out(i):
        a = prefix[i]
        b = suffix[i + db.size[i]]
        return a if a > b else b

    top = max(s)
    tied = [False] * n
    tied_above = [False] * n
    heads = []
    for i in range(n):
        tied[i] = s[i] >= top - 1e-9
        if i:
            tied_above[i] = tied_above[parent[i]] or tied[parent[i]]
        if tied[i] and not tied_above[i]:
            heads.append(i)
    best = heads[0]
    for h in heads[1:]:
        a, b = best, h
        while db.depth[a] > db.depth[b]:
            a = parent[a]
        while db.depth[b] > db.depth[a]:
            b = parent[b]
        while a != b:
            a, b = parent[a], parent[b]
        best = a

    threshold = math.log(min_support / (1.0 - min_support))
    path = db.path(best)
    margins = []
    for node in path:
        out = best_out(node)
        margins.append(float("inf") if out == neg else best_in[node] - out)
    confident = 0
    for k, margin in enumerate(margins):
        if margin >= threshold:
            confident = k
    return {
        "best": best,
        "heads": heads,
        "path": path,
        "margins": margins,
        "terminal": path[confident],
        "confident_len": confident + 1,
    }


def support_from_margin(margin):
    if margin == float("inf"):
        return 1.0
    if margin > 700:
        return 1.0
    return 1.0 / (1.0 + math.exp(-margin))


def analyse(sample, db, args):
    w_unique = log_odds(args.error_rate)
    w_recurrent = log_odds(max(args.recurrent_error_rate, args.error_rate))
    mode, hits, use_complement = match_sample(sample, db, args.build, args.complement)
    obs, other, flipped, ambiguous = classify(hits, use_complement, w_unique, w_recurrent, args.exclude)
    x_het_rate = sample.x_het / sample.x_called if sample.x_called else None
    qc = {
        "y_rows": sample.y_rows,
        "y_called": sample.y_called,
        "y_no_call": sample.y_nocall,
        "y_heterozygous": sample.y_het,
        "y_indel": sample.y_indel,
        "y_conflicting_duplicates": len(sample.conflicting_pos),
        "tree_sites_matched": len({m.pos37 for m, c in hits}),
        "informative_sites": len({o[0].pos37 for o in obs}),
        "informative_calls": len(obs),
        "unexpected_alleles": other,
        "strand_flipped_calls": flipped,
        "strand_ambiguous_skipped": ambiguous,
        "x_called": sample.x_called,
        "x_heterozygous_rate": round(x_het_rate, 4) if x_het_rate is not None else None,
    }
    warnings = []
    if sample.y_called and sample.y_het > 0.05 * (sample.y_called + sample.y_het):
        warnings.append(f"{sample.y_het} heterozygous Y calls ({sample.y_het / (sample.y_called + sample.y_het):.0%}); "
                        "possible contamination or a female sample")
    if x_het_rate is not None and x_het_rate > 0.05 and sample.x_called >= 100:
        warnings.append(f"X-chromosome heterozygosity is {x_het_rate:.1%}; male samples are normally below 1%")
    if use_complement:
        warnings.append(f"{flipped} calls matched only on the opposite strand and were complemented; "
                        f"{ambiguous} A/T or C/G markers were skipped because their strand cannot be told")
    if mode == "rsID":
        warnings.append("positions are not GRCh37/GRCh38, so markers were matched by rsID only"
                        + (" (file declares build 36)" if sample.build_hint == 36 else ""))
    result = {
        "file": sample.path,
        "vendor": sample.vendor,
        "input": sample.kind,
        "vcf_sample": sample.vcf_sample,
        "coordinates": mode,
        "build_hint": sample.build_hint,
        "tree": db.version,
        "parameters": {"error_rate": args.error_rate, "recurrent_error_rate": args.recurrent_error_rate,
                       "min_support": args.min_support},
        "qc": qc,
        "warnings": warnings,
    }
    derived_total = sum(1 for o in obs if o[2])
    if derived_total == 0:
        if sample.y_rows == 0:
            reason = "the file has no Y-chromosome rows"
        elif sample.y_called < 0.1 * sample.y_rows:
            reason = "almost all Y-chromosome calls are missing, the pattern of a female sample"
            if x_het_rate is not None and x_het_rate > 0.05:
                reason += f" (X heterozygosity {x_het_rate:.1%})"
        elif not obs:
            reason = "no Y-chromosome call matched a marker in the tree"
        else:
            reason = (f"all {len(obs)} informative calls are ancestral, so the file's markers "
                      "do not reach this lineage")
        result.update({"status": "no_result", "reason": reason})
        return result

    fit = place(db, obs, args.min_support)
    best = fit["best"]
    terminal = fit["terminal"]
    if terminal == 0:
        p = support_from_margin(fit["margins"][-1])
        result.update({"status": "no_result",
                       "reason": f"the evidence is too weak to place the sample (best branch {db.ids[best]} "
                                 f"at {fmt_support(p)} support)"})
        return result
    on_best_path = set(fit["path"])
    node_obs = {}
    for o in obs:
        node_obs.setdefault(o[0].node, []).append(o)
    site_obs = {}
    for o in obs:
        site_obs.setdefault(o[0].pos37, []).append(o)

    def describe(o):
        m, call, derived, w = o
        return {"snp": m.name, "names": m.names, "branch": db.ids[m.node], "grch37": m.pos37,
                "grch38": m.pos38 or None, "ancestral": m.anc, "derived": m.der, "call": call,
                "state": "derived" if derived else "ancestral",
                "recurrent": m.recurrent, "rsids": m.rsids}

    path_rows = []
    for k, node in enumerate(fit["path"]):
        items = node_obs.get(node, [])
        path_rows.append({
            "id": db.ids[node],
            "derived": sum(1 for o in items if o[2]),
            "ancestral": sum(1 for o in items if not o[2]),
            "support": support_from_margin(fit["margins"][k]),
            "confident": k < fit["confident_len"],
            "formed_ybp": db.formed[node] if db.formed[node] > 0 else None,
            "tmrca_ybp": db.tmrca[node] if db.tmrca[node] > 0 else None,
            "markers": [describe(o) for o in items],
        })

    ancestral_on_path = []
    derived_off_path = []
    unresolved_below = []
    path_rank = {node: k for k, node in enumerate(fit["path"])}

    def site_entry(items):
        entry = describe(items[0])
        entry["branch"] = ", ".join(db.ids[o[0].node] for o in items)
        entry["major"] = ", ".join(sorted({db.major(o[0].node) for o in items}))
        return entry

    for pos, items in site_obs.items():
        derived_items = [o for o in items if o[2]]
        if derived_items:
            if any(o[0].node in on_best_path for o in derived_items):
                continue
            if any(db.contains(best, o[0].node) for o in derived_items):
                unresolved_below.append(site_entry(derived_items))
            else:
                derived_off_path.append(site_entry(derived_items))
        else:
            on = [o for o in items if o[0].node in on_best_path]
            if on:
                entry = site_entry(on)
                entry["rank"] = min(path_rank[o[0].node] for o in on)
                ancestral_on_path.append(entry)
    ancestral_on_path.sort(key=lambda c: c.pop("rank"))
    derived_off_path.sort(key=lambda c: (c["major"], c["branch"]))

    sub_d = [0] * db.n
    sub_a = [0] * db.n
    for node, items in node_obs.items():
        d = sum(1 for o in items if o[2])
        a = len(items) - d
        x = node
        while x >= 0:
            sub_d[x] += d
            sub_a[x] += a
            x = db.parent[x]
    subclades = []
    untested = 0
    for child in db.children(terminal):
        own = node_obs.get(child, [])
        own_d = sum(1 for o in own if o[2])
        own_a = len(own) - own_d
        if not sub_d[child] and not sub_a[child]:
            untested += 1
            continue
        if sub_d[child]:
            status = "derived_unconfirmed"
        elif own_a:
            status = "ancestral"
        else:
            status = "downstream_ancestral"
        downstream_snps = []
        if status == "downstream_ancestral":
            stack = [child]
            while stack and len(downstream_snps) < 6:
                x = stack.pop()
                downstream_snps.extend(o[0].name for o in node_obs.get(x, []) if not o[2])
                stack.extend(db.children(x))
        subclades.append({
            "id": db.ids[child],
            "status": status,
            "derived": own_d,
            "ancestral": own_a,
            "subtree_derived": sub_d[child],
            "subtree_ancestral": sub_a[child],
            "snps": [o[0].name + ("+" if o[2] else "-") for o in own][:6],
            "downstream_snps": downstream_snps[:6],
        })
    order = {"derived_unconfirmed": 0, "ancestral": 1, "downstream_ancestral": 2}
    subclades.sort(key=lambda s: (order[s["status"]], -s["subtree_ancestral"] - s["subtree_derived"]))

    margin = fit["margins"][fit["confident_len"] - 1]
    result.update({
        "status": "ok",
        "haplogroup": db.ids[terminal],
        "major": db.major(terminal),
        "support": support_from_margin(margin),
        "margin_log_odds": None if margin == float("inf") else round(margin, 3),
        "formed_ybp": db.formed[terminal] if db.formed[terminal] > 0 else None,
        "tmrca_ybp": db.tmrca[terminal] if db.tmrca[terminal] > 0 else None,
        "best_scoring_branch": db.ids[best],
        "ties": [db.ids[h] for h in fit["heads"]] if len(fit["heads"]) > 1 else [],
        "path": path_rows,
        "conflicts": {"ancestral_on_path": ancestral_on_path, "derived_off_path": derived_off_path},
        "unresolved_below": unresolved_below,
        "subclades": subclades,
        "subclades_untested": untested,
    })
    return result


def fmt_int(n):
    return f"{n:,}"


def plural(n, one, many):
    return f"{n:,} {one if n == 1 else many}"


def fmt_support(p):
    if p >= 0.9999:
        return ">99.99%"
    return f"{p * 100:.2f}%"


def render(result, style, verbose):
    out = []
    add = out.append
    add(style.bold(result["file"]))
    qc = result["qc"]
    source = result["vendor"] or ("VCF" if result["input"] == "vcf" else "unrecognised vendor")
    if result.get("vcf_sample"):
        source += f" sample {result['vcf_sample']}"
    coords = {"GRCh37": "GRCh37 positions", "GRCh38": "GRCh38 positions", "rsID": "rsID"}
    add(f"  Source        {source}, markers matched by {coords.get(result['coordinates'], 'nothing')}")
    add(f"  Y calls       {fmt_int(qc['y_called'])} of {fmt_int(qc['y_rows'])} rows called"
        + (f", {fmt_int(qc['y_heterozygous'])} heterozygous" if qc["y_heterozygous"] else "")
        + f"; {fmt_int(qc['informative_sites'])} tree SNPs informative"
        + (f", {fmt_int(qc['unexpected_alleles'])} with unexpected alleles" if qc["unexpected_alleles"] else ""))
    for w in result.get("warnings", []):
        add(f"  Warning       {w}")
    if result["status"] != "ok":
        add(f"  Result        {style('no Y haplogroup', '31')}: {result['reason']}")
        return "\n".join(out)

    support = result["support"]
    add(f"  Haplogroup    {style.bold(result['haplogroup'])}  (major clade {result['major']})")
    add(f"  Support       {style.support(fmt_support(support), support)}")
    ages = []
    if result["formed_ybp"] is not None:
        ages.append(f"formed {fmt_int(result['formed_ybp'])} ybp")
    if result["tmrca_ybp"] is not None:
        ages.append(f"TMRCA {fmt_int(result['tmrca_ybp'])} ybp")
    if ages:
        add(f"  YFull age     {', '.join(ages)}")
    if result["ties"]:
        add(f"  Ambiguous     equally likely branches: {', '.join(result['ties'])}")

    rows = result["path"]
    start = 0
    if not verbose:
        letter = result["major"][0]
        ids = [r["id"] for r in rows]
        if letter in ids:
            start = ids.index(letter)
        else:
            start = next((k for k, i in enumerate(ids) if k and i.startswith(letter)), 0)
    head, tail = rows[:start], rows[start:]
    shown = [r for r in tail if verbose or r["derived"] or r["ancestral"] or r["id"] == result["haplogroup"]]
    width = max([len(r["id"]) + 2 for r in shown] + [12]) + 2
    add("")
    add(style.dim(f"  {'branch':<{width}}{'derived':>8}{'ancestral':>10}  {'support':>8}  SNPs"))
    if head:
        d = sum(r["derived"] for r in head)
        a = sum(r["ancestral"] for r in head)
        p = min(r["support"] for r in head)
        add(f"  {'root..' + head[-1]['id']:<{width}}{d:>8}{a:>10}  {fmt_support(p):>8}  "
            f"{plural(len(head), 'branch', 'branches')} above {tail[0]['id'] if tail else ''}")
    for r in shown:
        names = [x["snp"] for x in r["markers"] if x["state"] == "derived"][:4]
        neg = [x["snp"] + "-" for x in r["markers"] if x["state"] == "ancestral"][:3]
        label = r["id"] + ("" if r["confident"] else " ?")
        line = (f"  {label:<{width}}{r['derived']:>8}{r['ancestral']:>10}  "
                f"{fmt_support(r['support']):>8}  {', '.join(names + neg)}")
        add(line if r["confident"] else style.dim(line))
    hidden = len(tail) - len(shown)
    if hidden:
        add(style.dim(f"  ({plural(hidden, 'branch', 'branches')} on this path without markers in the file; -v lists them)"))
    if any(not r["confident"] for r in rows):
        add(style.dim(f"  ? = below the {result['parameters']['min_support']:.0%} support threshold, not reported"))

    subs = result["subclades"]
    if subs or result["subclades_untested"]:
        add("")
        add(f"  Subclades of {result['haplogroup']}")
        limit = None if verbose else 8
        for s in subs[:limit]:
            if s["status"] == "derived_unconfirmed":
                text = (f"{s['subtree_derived']} derived, {s['subtree_ancestral']} ancestral in this clade, "
                        "not enough to report")
            elif s["status"] == "ancestral":
                text = "ancestral: " + ", ".join(s["snps"])
            else:
                text = "not in the file; downstream SNPs ancestral: " + ", ".join(s["downstream_snps"])
            add(f"    {s['id']:<{max(12, width - 2)}}{text}")
        if limit and len(subs) > limit:
            add(style.dim(f"    ... {plural(len(subs) - limit, 'more tested subclade', 'more tested subclades')} (-v lists them)"))
        if result["subclades_untested"]:
            add(style.dim(f"    {plural(result['subclades_untested'], 'subclade', 'subclades')} without markers in this file"))

    conflicts = result["conflicts"]
    n_conf = len(conflicts["ancestral_on_path"]) + len(conflicts["derived_off_path"])
    if n_conf:
        add("")
        add(f"  Calls that disagree with this path: {n_conf}")
        limit = None if verbose else 6
        for c in conflicts["ancestral_on_path"][:limit]:
            add(f"    {c['snp']:<12} ancestral ({c['call']}) at {c['branch']}, which is on the path"
                + (" [recurrent]" if c["recurrent"] else ""))
        for c in conflicts["derived_off_path"][:limit]:
            add(f"    {c['snp']:<12} derived ({c['call']}) at {c['branch']} ({c['major']})"
                + (" [recurrent]" if c["recurrent"] else ""))
        rest = n_conf - len(conflicts["ancestral_on_path"][:limit]) - len(conflicts["derived_off_path"][:limit])
        if rest > 0:
            add(style.dim(f"    ... {rest} more (-v or --json lists all)"))
    return "\n".join(out)


def summary_line(result):
    if result["status"] != "ok":
        return "\t".join([result["file"], "-", "-", "-", str(result["qc"]["informative_sites"]), result["reason"]])
    return "\t".join([result["file"], result["haplogroup"], result["major"], f"{result['support']:.6f}",
                      str(result["qc"]["informative_sites"]), result["coordinates"]])


def snp_report(db, queries, samples, style):
    lines = []
    for query in queries:
        is_rs = query.startswith("RS") and query[2:].isdigit()
        found = [m for m in db.markers
                 if (is_rs and query.lower() in m.rsids)
                 or (not is_rs and query in (n.upper() for n in m.names.split("/")))]
        if not found:
            lines.append(f"{query}: not in the tree database")
            continue
        for m in found:
            label = query.lower() if is_rs else next(n for n in m.names.split("/") if n.upper() == query)
            rs = f"  {','.join(m.rsids)}" if m.rsids and not is_rs else ""
            pos38 = f" GRCh38:{m.pos38}" if m.pos38 else ""
            lines.append(f"{style.bold(label)}  branch {db.ids[m.node]} ({db.major(m.node)})  "
                         f"GRCh37:{m.pos37}{pos38}  {m.anc}->{m.der}{rs}  [{m.names}]"
                         + ("  [recurrent]" if m.recurrent else ""))
            for s in samples:
                call = s.by_pos.get(m.pos37) or (s.by_pos.get(m.pos38) if m.pos38 else None) \
                    or next((s.by_id[r] for r in m.rsids if r in s.by_id), None)
                if call is None:
                    state = "not in file or no call"
                elif call == m.der:
                    state = f"{call} derived"
                elif call == m.anc:
                    state = f"{call} ancestral"
                else:
                    state = f"{call} matches neither allele"
                lines.append(f"    {s.label}: {state}")
    return "\n".join(lines)


def node_report(db, query, style):
    idx = db.index_of(query)
    if idx is None:
        hits = [m.node for m in db.markers if query.upper() in (n.upper() for n in m.names.split("/"))]
        idx = hits[0] if hits else None
    if idx is None:
        return f"{query}: no branch or SNP with that name"
    lines = [style.bold(db.ids[idx]) + f"  (major clade {db.major(idx)})"]
    ages = []
    if db.formed[idx] > 0:
        ages.append(f"formed {fmt_int(db.formed[idx])} ybp")
    if db.tmrca[idx] > 0:
        ages.append(f"TMRCA {fmt_int(db.tmrca[idx])} ybp")
    if ages:
        lines.append("  " + ", ".join(ages))
    lines.append("  path: " + " > ".join(db.ids[i] for i in db.path(idx)[1:]))
    kids = db.children(idx)
    if kids:
        lines.append(f"  {len(kids)} direct subclades: " + ", ".join(db.ids[k] for k in kids[:40])
                     + (" ..." if len(kids) > 40 else ""))
    lines.append(f"  {fmt_int(db.size[idx] - 1)} branches below")
    return "\n".join(lines)


def clean_path(text):
    text = text.strip()
    if len(text) >= 2 and text[0] == text[-1] and text[0] in "'\"":
        text = text[1:-1]
    return os.path.expanduser(text.replace("\\ ", " "))


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Predict a Y-chromosome haplogroup from a raw DNA file (23andMe, AncestryDNA, FTDNA, "
                    "MyHeritage, LivingDNA, VCF, ...), offline.")
    ap.add_argument("files", nargs="*", help="raw data files (.txt/.csv/.vcf, optionally .gz/.bz2/.zip)")
    ap.add_argument("--db", default=DEFAULT_DB, help="tree database (default: ydb.tsv.gz next to this script)")
    ap.add_argument("--build", choices=["auto", "GRCh37", "GRCh38", "rsID"], default="auto",
                    help="coordinate system of the file (default: detected from the data)")
    ap.add_argument("--error-rate", type=float, default=0.01, help="per-call genotype error rate (default 0.01)")
    ap.add_argument("--recurrent-error-rate", type=float, default=0.1,
                    help="error rate for markers that occur on more than one branch (default 0.1)")
    ap.add_argument("--min-support", type=float, default=0.95,
                    help="clade support required to report a branch (default 0.95)")
    ap.add_argument("--complement", choices=["auto", "yes", "no"], default="auto",
                    help="accept reverse-strand calls (default: only when the file shows a strand problem)")
    ap.add_argument("--exclude", default="", help="comma-separated SNP names to ignore")
    ap.add_argument("--sample", help="sample column to read from a multi-sample VCF")
    ap.add_argument("--snp", default="", help="show calls for these SNP names (comma-separated)")
    ap.add_argument("--node", help="print a branch (YFull ID or SNP name) with its path and subclades")
    ap.add_argument("--json", action="store_true", help="write JSON instead of text")
    ap.add_argument("--summary", action="store_true", help="one tab-separated line per file")
    ap.add_argument("-v", "--verbose", action="store_true", help="list every branch and conflict")
    ap.add_argument("--no-color", action="store_true")
    ap.add_argument("--version", action="version", version=f"%(prog)s {__version__}")
    args = ap.parse_args(argv)

    for name, value in (("--error-rate", args.error_rate), ("--recurrent-error-rate", args.recurrent_error_rate),
                        ("--min-support", args.min_support)):
        if not 0.0 < value < 1.0:
            ap.error(f"{name} must be between 0 and 1")
    args.exclude = {s.strip().upper() for s in args.exclude.split(",") if s.strip()}
    snp_names = [s.strip().upper() for s in args.snp.replace(" ", ",").split(",") if s.strip()]
    color = sys.stdout.isatty() and not args.no_color and "NO_COLOR" not in os.environ and not args.json
    if color and os.name == "nt":
        os.system("")
    style = Style(color)

    files = [clean_path(f) for f in args.files]
    if not files and not args.node and not snp_names:
        try:
            entered = input("Path to raw DNA file: ")
        except EOFError:
            return 1
        files = [clean_path(entered)] if entered.strip() else []
        if not files:
            return 1

    samples = []
    failures = []
    for path in files:
        if not os.path.isfile(path):
            failures.append({"file": path, "status": "error", "reason": "file not found"})
            continue
        try:
            samples.append(read_sample(path, args.sample))
        except (OSError, ValueError, zipfile.BadZipFile, EOFError) as e:
            failures.append({"file": path, "status": "error", "reason": str(e)})

    want_pos = set()
    want_ids = set()
    for s in samples:
        want_pos.update(s.by_pos)
        want_ids.update(s.by_id)
    want_names = {n for n in snp_names if not (n.startswith("RS") and n[2:].isdigit())}
    want_ids.update(n.lower() for n in snp_names if n.startswith("RS") and n[2:].isdigit())
    if args.node:
        want_names.add(args.node.upper())
    try:
        db = TreeDB(args.db, want_pos, want_ids, want_names)
    except (OSError, ValueError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2

    if args.node:
        print(node_report(db, args.node, style))
        if not files:
            return 0
        print()
    if snp_names:
        print(snp_report(db, snp_names, samples, style))
        if not samples:
            return 0
        print()

    results = [analyse(s, db, args) for s in samples]
    results.extend(failures)
    if args.json:
        print(json.dumps(results if len(results) != 1 else results[0], indent=1))
    elif args.summary:
        print("file\thaplogroup\tmajor\tsupport\tinformative_snps\tmatched_by")
        for r in results:
            if r["status"] == "error":
                print(f"{r['file']}\t-\t-\t-\t0\terror: {r['reason']}")
            else:
                print(summary_line(r))
    else:
        for i, r in enumerate(results):
            if i:
                print()
            if r["status"] == "error":
                print(f"{style.bold(r['file'])}\n  error: {r['reason']}")
            else:
                print(render(r, style, args.verbose))
        if results and all(r["status"] == "ok" for r in results):
            print()
            print(style.dim(f"  Tree: {db.version}. Support = L(in) / (L(in) + L(out)) for the best placement "
                            f"inside vs outside each clade, at a {args.error_rate * 100:g}% per-call error rate."))
    return 0 if results and all(r["status"] == "ok" for r in results) else 1


if __name__ == "__main__":
    sys.exit(main())
