#!/usr/bin/env python3
"""
Y-chromosome haplogroup predictor for consumer raw DNA files.

Reads 23andMe, AncestryDNA, FamilyTreeDNA, MyHeritage, LivingDNA, tellmeGen,
Genes for Good, Illumina GSA reports and single-sample VCF files (plain, .gz,
.bz2 or .zip) and places the sample on the YFull Y-SNP tree. Runs offline.

Method
  Every tree marker found in the file is scored as derived or ancestral. For a
  candidate haplogroup h, a marker is expected to be derived when its branch
  lies on the path from the root to h and ancestral otherwise. Each call that
  contradicts that expectation costs log((1 - e) / e), with e = --error-rate
  (--recurrent-error-rate for markers that occur on several branches or are
  known to misbehave). Clade support is L(in) / (L(in) + L(out)), where L(in)
  and L(out) are the likelihoods of the best placements inside and outside the
  clade. The reported haplogroup is the deepest branch on the best path whose
  support reaches --min-support.

Data
  ydb.tsv.gz, generated by build-ydb.py:
    tree       YFull YTree (github.com/YFullTeam/YTree), CC BY 4.0
    positions  Yleaf position tables (github.com/genid/Yleaf), GPL-3.0
"""

