class Style:
    def __init__(self, enabled):
        self.enabled = enabled

    def __call__(self, text, code):
        return f"\033[{code}m{text}\033[0m" if self.enabled else text

    def bold(self, text):
        return self(text, "1")

    def dim(self, text):
        return self(text, "2")

    def support(self, text, p):
        return self(text, "32" if p >= 0.99 else "33" if p >= 0.9 else "31")


class Sample:
    def __init__(self, path):
        self.path = path
        self.label = os.path.basename(path)
        self.vendor = None
        self.kind = "table"
        self.name = None
        self.contig_hint = None
        self.by_pos = {}
        self.conflicting_pos = set()
        self.ref_bases = {}
        self.dropped = set()
        self.blocked = set()
        self.ref_blocks = []
        self.fill = False
        self.fill_ranges = [(1, MT_LENGTH)]
        self.from_alleles = []
        self.sequence = None
        self.sequence_info = None
        self.filter_ignored = None
        self.rows = 0
        self.called = 0
        self.nocall = 0
        self.het = 0
        self.indel = 0
        self.filtered = 0
        self.variant_rows = 0
        self.listed = 0

    def call(self, pos, base):
        if not pos or pos in self.conflicting_pos:
            return
        if pos in self.by_pos and self.by_pos[pos] != base:
            del self.by_pos[pos]
            self.conflicting_pos.add(pos)
            self.blocked.add(pos)
        else:
            self.by_pos[pos] = base

    def add(self, pos, base, status):
        self.rows += 1
        if status == "call":
            self.called += 1
            self.call(pos, base)
        elif status == "het":
            self.het += 1
            self.dropped.add(pos)
        elif status == "filtered":
            self.filtered += 1
            self.blocked.add(pos)
        elif status == "indel":
            self.indel += 1
            self.blocked.add(pos)
        else:
            self.nocall += 1
            self.blocked.add(pos)


def open_text(path):
    with open(path, "rb") as f:
        magic = f.read(4)
    if magic[:2] == b"\x1f\x8b":
        raw = gzip.open(path, "rb")
    elif magic[:3] == b"BZh":
        raw = bz2.open(path, "rb")
    elif magic == b"PK\x03\x04":
        archive = zipfile.ZipFile(path)
        members = [m for m in archive.infolist()
                   if not m.is_dir() and not os.path.basename(m.filename).startswith(".")
                   and "__MACOSX" not in m.filename]
        if not members:
            raise ValueError("zip archive contains no files")
        member = max(members, key=lambda m: m.file_size)
        with archive.open(member) as probe:
            inner = probe.read(2)
        raw = archive.open(member)
        if inner == b"\x1f\x8b":
            raw = gzip.GzipFile(fileobj=raw)
    else:
        raw = open(path, "rb")
    head = raw.peek(2)[:2] if hasattr(raw, "peek") else b""
    encoding = "utf-16" if head in (b"\xff\xfe", b"\xfe\xff") else "utf-8-sig"
    return io.TextIOWrapper(raw, encoding=encoding, errors="replace", newline=None)


def norm_chrom(text):
    c = text.strip().strip('"').upper()
    if c.startswith("CHR"):
        c = c[3:]
    return CHROM_ALIASES.get(c, c)


def parse_genotype(text):
    g = text.strip().upper()
    for ch in " /|;:\"'":
        g = g.replace(ch, "")
    if g in NO_CALL:
        return None, "nocall"
    if len(g) == 1:
        if g in BASES:
            return g, "call"
        return None, "indel" if g in "ID" else "nocall"
    if len(g) == 2:
        a, b = g
        if a in BASES and b in BASES:
            return (a, "call") if a == b else (None, "het")
        if a in BASES and b in "0-N":
            return a, "call"
        if b in BASES and a in "0-N":
            return b, "call"
        if a in "ID" and b in "ID":
            return None, "indel"
    return None, "nocall"


def parse_mutation(token):
    """Read one mtDNA variant as written in HaploGrep, PhyloTree, YFull or FTDNA lists.

    Returns (kind, start, end, base, before) with kind sub, het, nocall, del or ins, or None.
    73G and A73G are substitutions; 16189 alone is a transition; 315.1C an insertion;
    523d and 8281-8289d deletions; 16129R a heteroplasmy."""
    t = token.strip().strip("()[]").upper().rstrip("!")
    if t.startswith("M.") or t.startswith("MT:"):
        t = t.split(".", 1)[1] if t.startswith("M.") else t[3:]
    m = MUT_DEL.match(t)
    if m:
        start = int(m[2])
        end = int(m[3]) if m[3] else start + max(len(m[1]), 1) - 1
        return ("del", start, end, None, None) if 0 < start <= end <= MT_LENGTH else None
    m = MUT_INS.match(t)
    if m:
        pos = int(m[2])
        return ("ins", pos, pos, None, None) if 0 < pos <= MT_LENGTH else None
    m = MUT_ARROW.match(t)
    if m:
        pos = int(m[1])
        return ("sub", pos, pos, m[3], m[2]) if 0 < pos <= MT_LENGTH else None
    m = MUT_SUB.match(t)
    if m:
        pos = int(m[2])
        if not 0 < pos <= MT_LENGTH:
            return None
        base = m[3] or ""
        kind = "sub" if base in BASES or not base else "nocall" if base == "N" else "het"
        return kind, pos, pos, base or None, m[1] or None
    return None


def parse_ranges(text):
    ranges = []
    for part in text.split(";"):
        part = part.strip()
        if not part:
            continue
        a, b = (int(x) for x in part.split("-"))
        if a <= b:
            ranges.append((max(a, 1), min(b, MT_LENGTH)))
        else:
            ranges.extend([(a, MT_LENGTH), (1, b)])
    return ranges or [(1, MT_LENGTH)]


def split_fields(line):
    if "\t" in line:
        return [f.strip().strip('"').strip() for f in line.split("\t")]
    if "," in line:
        return [f.strip() for f in line.replace('"', "").split(",")]
    return line.split()


def map_columns(fields):
    cols = {}
    for i, name in enumerate(f.lower().lstrip("#").replace("_", " ").strip() for f in fields):
        if name in ID_COLUMNS:
            cols.setdefault("id", i)
        elif name in CHROM_COLUMNS:
            cols.setdefault("chrom", i)
        elif name in POS_COLUMNS or name.startswith("position"):
            cols.setdefault("pos", i)
        elif name in GENOTYPE_COLUMNS:
            cols.setdefault("gt", i)
        elif name.replace(" ", "").startswith("allele1"):
            cols.setdefault("a1", i)
        elif name.replace(" ", "").startswith("allele2"):
            cols.setdefault("a2", i)
    if "chrom" in cols and "pos" in cols and ("gt" in cols or "a1" in cols):
        return cols
    return None


def guess_columns(fields):
    if len(fields) >= 4 and fields[2].isdigit():
        if len(fields) == 4:
            return {"id": 0, "chrom": 1, "pos": 2, "gt": 3}
        return {"id": 0, "chrom": 1, "pos": 2, "a1": 3, "a2": 4}
    return None


def note_header(sample, text):
    low = text.lower()
    if sample.vendor is None:
        for key, vendor in VENDOR_HINTS:
            if key in low:
                sample.vendor = vendor
                break


def detect_format(head):
    content = [line.strip() for line in head if line.strip()]
    if not content:
        return "table"
    if content[0].startswith(">"):
        return "fasta"
    if any(line.startswith("##fileformat=VCF") or line.startswith("#CHROM") for line in content):
        return "table"
    data = [line for line in content if not line.startswith("#")]
    if data and all(SEQUENCE_LINE.match(line) for line in data[:20]) and sum(map(len, data[:20])) >= 200:
        return "fasta"
    for line in data[:5]:
        fields = line.split("\t")
        if len(fields) >= 2 and (RANGE.match(fields[1]) or fields[1].strip().lower() == "range"):
            return "hsd"
    words = [w for line in data for w in re.split(r"[\s,;]+", line) if w]
    if words and all(parse_mutation(w) for w in words):
        return "list"
    return "table"


def vcf_alleles(gt):
    parts = gt.replace("|", "/").split("/")
    if any(p in (".", "") for p in parts):
        return None
    try:
        return [int(p) for p in parts]
    except ValueError:
        return None


def major_allele(indexes, fmt, values, n_alts, af_per_alt):
    """Allele index of a heteroplasmic call, or None when no allele reaches HETEROPLASMY_CALL."""
    distinct = list(dict.fromkeys(indexes))
    share = {}
    if "AF" in fmt and fmt.index("AF") < len(values):
        try:
            af = [float(x) for x in values[fmt.index("AF")].split(",")]
        except ValueError:
            af = []
        nonref = [i for i in distinct if i > 0]
        if af_per_alt and len(af) == n_alts:
            share = {i: af[i - 1] for i in nonref}
        elif len(af) == len(nonref):
            share = dict(zip(nonref, af))
        if share and 0 in distinct:
            share[0] = max(0.0, 1.0 - sum(share.values()))
    if not share and "AD" in fmt and fmt.index("AD") < len(values):
        try:
            depth = [int(x) for x in values[fmt.index("AD")].split(",")]
        except ValueError:
            depth = []
        if depth and sum(depth) > 0 and len(depth) == n_alts + 1:
            share = {i: depth[i] / sum(depth) for i in distinct}
    if share:
        best = max(share, key=share.get)
        if share[best] >= HETEROPLASMY_CALL:
            return best
    return None


def add_vcf_allele(sample, pos, ref, allele):
    if allele == "*":
        sample.add(pos, None, "indel")
        sample.dropped.add(pos)
        return
    if allele.startswith("<") or not allele:
        sample.add(pos, None, "nocall")
        return
    if len(ref) == 1 and len(allele) == 1:
        sample.add(pos, allele, "call" if allele in BASES else "nocall")
        return
    sample.rows += 1
    sample.indel += len(ref) != len(allele)
    sample.called += len(ref) == len(allele)
    for i in range(min(len(ref), len(allele))):
        if allele[i] in BASES:
            sample.call(pos + i, allele[i])
    sample.dropped.update(range(pos + len(allele), pos + len(ref)))


def add_vcf_row(sample, pos, ref, alts, fmt, values, indexes, af_per_alt):
    if indexes is None:
        sample.add(pos, None, "nocall")
        return
    alleles = [ref] + alts
    pick = indexes[0]
    if len(set(indexes)) > 1:
        pick = major_allele(indexes, fmt, values, len(alts), af_per_alt)
        if pick is None:
            sample.add(pos, None, "het")
            return
    if pick >= len(alleles):
        sample.add(pos, None, "nocall")
    elif pick == 0:
        sample.add(pos, ref[0], "call" if ref[0] in BASES else "nocall")
    else:
        add_vcf_allele(sample, pos, ref, alleles[pick])


def read_table(sample, lines, vcf_sample):
    cols = None
    vcf_index = None
    multi = False
    af_per_alt = False
    nonref_gt = re.compile(r"\t(?:0[/|])?[1-9]")
    held = []
    for raw in lines:
        line = raw.rstrip("\r\n")
        if not line.strip():
            continue
        if sample.kind == "table" and cols is None and (line.startswith("##fileformat=VCF") or line.startswith("#CHROM")):
            sample.kind = "vcf"
        if sample.kind == "vcf":
            if line.startswith("##"):
                note_header(sample, line)
                low = line.lower()
                if low.startswith("##contig=") and any(f"id={c}," in low for c in ("mt", "chrm", "chrmt", "m")):
                    for part in low.split(","):
                        if part.startswith("length="):
                            length = int("".join(ch for ch in part[7:] if ch.isdigit()) or 0)
                            sample.contig_hint = CONTIG_MT_LENGTH.get(length, sample.contig_hint)
                if low.startswith("##format=<id=af,") and "number=a" in low:
                    af_per_alt = True
                continue
            fields = line.split("\t")
            if line.startswith("#CHROM"):
                names = fields[9:]
                if not names:
                    raise ValueError("VCF has no sample columns")
                if vcf_sample is None:
                    vcf_index = 9
                elif vcf_sample in names:
                    vcf_index = 9 + names.index(vcf_sample)
                else:
                    raise ValueError(f"sample {vcf_sample} not in VCF ({', '.join(names[:5])}...)")
                multi = len(names) > 1
                sample.name = fields[vcf_index]
                continue
            if vcf_index is None or len(fields) <= vcf_index:
                continue
            if norm_chrom(fields[0]) != "MT" or not fields[1].isdigit():
                continue
            pos = int(fields[1])
            ref = fields[3].upper()
            alts = [] if fields[4] in (".", "") else fields[4].upper().split(",")
            fmt = fields[8].split(":")
            values = fields[vcf_index].split(":")
            gt = values[fmt.index("GT")] if "GT" in fmt and fmt.index("GT") < len(values) else "."
            indexes = vcf_alleles(gt)
            if alts and all(a in ("<NON_REF>", "<*>", "<X>") for a in alts):
                end = next((int(x[4:]) for x in fields[7].split(";") if x.startswith("END=") and x[4:].isdigit()), pos)
                if indexes and all(i == 0 for i in indexes):
                    sample.ref_blocks.append((pos, end))
                else:
                    sample.blocked.update(range(pos, end + 1))
                sample.fill = None
                continue
            if ref and ref[0] in BASES:
                sample.ref_bases[pos] = ref[0]
            if multi:
                sample.variant_rows += bool(nonref_gt.search(line, sum(len(x) + 1 for x in fields[:9]) - 1))
            else:
                sample.variant_rows += bool(indexes and any(i > 0 for i in indexes))
            row = (pos, ref, alts, fmt, values, indexes, af_per_alt)
            if fields[6] in ("PASS", ".", "", "RefCall"):
                add_vcf_row(sample, *row)
            else:
                held.append((fields[6], row))
            continue

        if line.startswith("#") or cols is None:
            fields = split_fields(line.lstrip("#").strip())
            header = map_columns(fields)
            if header:
                cols = header
                continue
            if line.startswith("#") or line.startswith("["):
                note_header(sample, line)
                continue
            if cols is None:
                cols = guess_columns(fields)
                if cols is None:
                    note_header(sample, line)
                    continue
        fields = split_fields(line)
        try:
            if norm_chrom(fields[cols["chrom"]]) != "MT":
                continue
            pos_text = fields[cols["pos"]]
            pos = int(pos_text) if pos_text.isdigit() else 0
            if "gt" in cols:
                base, status = parse_genotype(fields[cols["gt"]])
            else:
                a2 = fields[cols["a2"]] if "a2" in cols and cols["a2"] < len(fields) else ""
                base, status = parse_genotype(fields[cols["a1"]] + a2)
        except IndexError:
            continue
        sample.add(pos, base, status)
    # Rows that fail a filter count as no-calls, unless every row carries the same filter, which is then a
    # label (the 1000 Genomes chrMT release marks every genotype "fa", called from FASTA).
    labels = {label for label, _ in held}
    if held and not sample.rows and len(labels) == 1:
        sample.filter_ignored = labels.pop()
        for _, row in held:
            add_vcf_row(sample, *row)
    else:
        for _, row in held:
            sample.add(row[0], None, "filtered")
    if sample.kind == "vcf" and sample.fill is not None:
        # A file that lists only the positions where someone differs from the reference implies the
        # reference everywhere else. Array exports list mostly reference calls and imply nothing.
        sample.fill = sample.rows > 0 and sample.variant_rows >= 0.9 * sample.rows
    sample.fill = bool(sample.fill)


def read_fasta(sample, lines, name):
    sample.kind = "fasta"
    records = []
    current = None
    for raw in lines:
        line = raw.strip()
        if not line or line.startswith(";"):
            continue
        if line.startswith(">"):
            current = [line[1:].strip(), []]
            records.append(current)
            continue
        if current is None:
            current = ["", []]
            records.append(current)
        current[1].append(line)
    if not records:
        raise ValueError("FASTA file contains no sequence")
    record = records[0]
    if name is not None:
        record = next((r for r in records if r[0] == name or r[0].split()[:1] == [name]), None)
        if record is None:
            raise ValueError(f"sequence {name} not in FASTA ({', '.join(r[0].split()[0] for r in records[:5] if r[0])}...)")
    sample.name = record[0].split()[0] if record[0] else None
    sample.sequence = re.sub(r"[^A-Za-z\-.?*]", "", "".join(record[1])).upper().replace("U", "T")


def apply_mutations(sample, words):
    for word in words:
        mut = parse_mutation(word)
        if mut is None:
            continue
        kind, start, end, base, before = mut
        sample.listed += 1
        if kind == "sub":
            if base is None:
                sample.from_alleles.append((start, None, None))
            else:
                sample.call(start, base)
                sample.from_alleles.append((start, before, base))
        elif kind == "het":
            sample.het += 1
            sample.dropped.add(start)
        elif kind == "nocall":
            sample.blocked.add(start)
        elif kind == "del":
            sample.indel += 1
            sample.dropped.update(range(start, end + 1))


def read_hsd(sample, lines, name):
    sample.kind = "hsd"
    rows = []
    for raw in lines:
        line = raw.rstrip("\r\n")
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) < 2 or fields[1].strip().lower() == "range":
            continue
        rows.append(fields)
    if not rows:
        raise ValueError("HSD file contains no samples")
    row = rows[0]
    if name is not None:
        row = next((r for r in rows if r[0].strip() == name), None)
        if row is None:
            raise ValueError(f"sample {name} not in HSD file ({', '.join(r[0] for r in rows[:5])}...)")
    sample.name = row[0].strip()
    sample.fill = True
    sample.fill_ranges = parse_ranges(row[1])
    words = [w for field in row[3:] for w in field.split()]
    apply_mutations(sample, words)


def read_list(sample, lines):
    sample.kind = "list"
    sample.fill = True
    words = []
    for raw in lines:
        line = raw.strip()
        if line and not line.startswith("#"):
            words.extend(w for w in re.split(r"[\s,;]+", line) if w)
    apply_mutations(sample, words)


def read_sample(path, name=None):
    sample = Sample(path)
    with open_text(path) as f:
        head = list(itertools.islice(f, 200))
        kind = detect_format(head)
        lines = itertools.chain(head, f)
        if kind == "fasta":
            read_fasta(sample, lines, name)
        elif kind == "hsd":
            read_hsd(sample, lines, name)
        elif kind == "list":
            read_list(sample, lines)
        else:
            read_table(sample, lines, name)
    return sample


def increasing_chain(hits):
    tails = []
    tail_idx = []
    prev = [-1] * len(hits)
    for n, (_, i) in enumerate(hits):
        k = bisect.bisect_left(tails, i)
        if k == len(tails):
            tails.append(i)
            tail_idx.append(n)
        else:
            tails[k] = i
            tail_idx[k] = n
        prev[n] = tail_idx[k - 1] if k else -1
    chain = []
    n = tail_idx[-1] if tail_idx else -1
    while n >= 0:
        chain.append(hits[n])
        n = prev[n]
    return chain[::-1]


def needleman_wunsch(a, b):
    gap = -2
    prev = [j * gap for j in range(len(b) + 1)]
    trace = []
    for i in range(1, len(a) + 1):
        cur = [i * gap] + [0] * len(b)
        row = bytearray(len(b) + 1)
        ai = a[i - 1]
        for j in range(1, len(b) + 1):
            d = prev[j - 1] + (1 if ai == b[j - 1] else -1)
            u = prev[j] + gap
            left = cur[j - 1] + gap
            if d >= u and d >= left:
                cur[j] = d
            elif u >= left:
                cur[j] = u
                row[j] = 1
            else:
                cur[j] = left
                row[j] = 2
        trace.append(row)
        prev = cur
    out = [-1] * len(a)
    i, j = len(a), len(b)
    while i > 0 and j > 0:
        t = trace[i - 1][j]
        if t == 0:
            out[i - 1] = j - 1
            i -= 1
            j -= 1
        elif t == 1:
            i -= 1
        else:
            j -= 1
    return out


def align(seq, ref, k=20):
    """For each position of seq, the 0-based position of ref it aligns to, or -1.

    Anchors are k-mers found once in ref; the longest run of anchors in the same order in both
    sequences is kept and the stretches between anchors are aligned with Needleman-Wunsch."""
    index = {}
    for i in range(len(ref) - k + 1):
        word = ref[i:i + k]
        index[word] = -1 if word in index else i
    hits = []
    for j in range(len(seq) - k + 1):
        i = index.get(seq[j:j + k], -1)
        if i >= 0:
            hits.append((j, i))
    out = [-1] * len(seq)
    cols = []
    last_j = last_i = -1
    for j, i in increasing_chain(hits):
        for t in range(k):
            if j + t > last_j and i + t > last_i:
                cols.append((j + t, i + t))
                last_j, last_i = j + t, i + t
    if not cols:
        return out
    pj, pi = cols[0]
    for j, i in cols:
        if j - pj > 1 or i - pi > 1:
            a, b = seq[pj + 1:j], ref[pi + 1:i]
            if len(a) == len(b):
                for t in range(len(a)):
                    out[pj + 1 + t] = pi + 1 + t
            elif a and b and len(a) * len(b) <= 250000:
                for t, u in enumerate(needleman_wunsch(a, b)):
                    if u >= 0:
                        out[pj + 1 + t] = pi + 1 + u
        out[j] = i
        pj, pi = j, i
    j0, i0 = cols[0]
    for t in range(1, min(j0, i0) + 1):
        out[j0 - t] = i0 - t
    for t in range(1, min(len(seq) - 1 - pj, len(ref) - 1 - pi) + 1):
        out[pj + t] = pi + t
    return out


class Marker:
    __slots__ = ("node", "pos", "frm", "to", "back")

    def __init__(self, node, pos, frm, to, back):
        self.node = node
        self.pos = pos
        self.frm = frm
        self.to = to
        self.back = back

    @property
    def name(self):
        before = "" if self.frm == "?" else self.frm
        return f"{before}{self.pos}{'d' if self.to == '?' else self.to}{'!' * self.back}"


class TreeDB:
    def __init__(self, path):
        if not os.path.exists(path):
            raise FileNotFoundError(f"tree database not found: {path} (run build-mtdb.py or pass --db)")
        self.file = path
        self.meta = {}
        self.parent = []
        self.ids = []
        self.formed = []
        self.tmrca = []
        self.root = {}
        self.site_markers = {}
        with gzip.open(path, "rt", encoding="utf-8") as f:
            for line in f:
                c = line[0]
                if c == "#":
                    parts = line[1:].rstrip("\n").split("\t")
                    self.meta[parts[0]] = parts[1:]
                elif c == "N":
                    _, idx, parent, nid, formed, tmrca = line.rstrip("\n").split("\t")
                    self.parent.append(int(parent))
                    self.ids.append(nid)
                    self.formed.append(int(formed))
                    self.tmrca.append(int(tmrca))
                elif c == "R":
                    _, pos, allele = line.rstrip("\n").split("\t")
                    self.root[int(pos)] = allele
                else:
                    node, pos, change, back = line.rstrip("\n").split("\t")
                    pos = int(pos)
                    self.site_markers.setdefault(pos, []).append(Marker(int(node), pos, change[0], change[1], len(back)))
        if self.meta.get("mtdb", [""])[0] != "1":
            raise ValueError(f"{path} is not a version 1 mtDNA tree database; rebuild it with build-mtdb.py")
        self.rcrs = self.meta["rcrs"][0]
        self.hg19 = self.meta["hg19_chrM"][0]
        self.excluded = {int(x) for x in self.meta.get("excluded", [""])[0].split(",") if x}
        self.recurrence = {pos: sum(1 for m in ms if m.to != "?") for pos, ms in self.site_markers.items()}
        self.n = len(self.parent)
        self.depth = [0] * self.n
        for i in range(1, self.n):
            self.depth[i] = self.depth[self.parent[i]] + 1
        self.size = [1] * self.n
        for i in range(self.n - 1, 0, -1):
            self.size[self.parent[i]] += self.size[i]
        self._index = None
        self._children = None
        self._hg19_map = None
        self._alleles = {}

    @property
    def version(self):
        return " ".join(self.meta.get("tree", ["unknown"])[:1])

    def root_allele(self, pos):
        return self.root.get(pos) or self.rcrs[pos - 1]

    def alleles(self, pos):
        if pos not in self._alleles:
            found = {self.root_allele(pos)}
            for m in self.site_markers.get(pos, ()):
                found.update((m.frm, m.to))
            self._alleles[pos] = frozenset(found & BASES)
        return self._alleles[pos]

    def hg19_map(self):
        """hg19 chrM position -> rCRS position (0 where the two sequences do not align)."""
        if self._hg19_map is None:
            self._hg19_map = [0] + [i + 1 for i in align(self.hg19, self.rcrs)]
        return self._hg19_map

    def index_of(self, node_id):
        if self._index is None:
            self._index = {nid.upper(): i for i, nid in enumerate(self.ids)}
        return self._index.get(node_id.upper())

    def children(self, node):
        if self._children is None:
            self._children = [[] for _ in range(self.n)]
            for i in range(1, self.n):
                self._children[self.parent[i]].append(i)
        return self._children[node]

    def path(self, node):
        out = []
        while node >= 0:
            out.append(node)
            node = self.parent[node]
        return out[::-1]

    def contains(self, clade, node):
        return clade <= node < clade + self.size[clade]

    def major(self, node):
        for i in reversed(self.path(node)):
            if MAJOR_NAME.match(self.ids[i]):
                return self.ids[i]
        return self.ids[node]

    def last_change(self, node, pos):
        """The deepest mutation at pos on the path from the root to node, or None."""
        best = None
        for m in self.site_markers.get(pos, ()):
            if self.contains(m.node, node) and (best is None or self.depth[m.node] >= self.depth[best.node]):
                best = m
        return best

    def expected(self, node, pos):
        m = self.last_change(node, pos)
        return m.to if m else self.root_allele(pos)

    def motif(self, node):
        """Differences from the rCRS expected on this branch, in HaploGrep notation."""
        out = []
        for pos in sorted(self.site_markers):
            allele = self.expected(node, pos)
            if allele == "?":
                out.append(f"{pos}d")
            elif allele != self.rcrs[pos - 1]:
                out.append(f"{pos}{allele}")
        return out


def choose_coordinates(sample, db, requested):
    if requested != "auto":
        return requested
    evidence = sample.ref_bases or sample.by_pos
    if not evidence:
        return sample.contig_hint or "rCRS"
    score = {}
    for mode, seq in (("rCRS", db.rcrs), ("hg19", db.hg19)):
        same = flipped = 0
        for p, b in evidence.items():
            if 0 < p <= len(seq):
                same += seq[p - 1] == b
                flipped += seq[p - 1] == COMPLEMENT.get(b)
        score[mode] = max(same, flipped)
    hint = sample.contig_hint or "rCRS"
    return max(score, key=lambda m: (score[m], m == hint, m == "rCRS"))


def align_sequence(sample, db):
    seq = sample.sequence
    ref = db.rcrs
    if len(seq) == len(ref) and ("-" in seq or sum(a == b for a, b in zip(seq, ref)) >= 0.95 * len(ref)):
        mapping = list(range(len(seq)))
    else:
        seq = seq.replace("-", "").replace(".", "")
        mapping = align(seq, ref)
    covered = set()
    gaps = 0
    for j, i in enumerate(mapping):
        if i < 0:
            continue
        b = seq[j]
        p = i + 1
        covered.add(p)
        if b in BASES:
            sample.call(p, b)
        elif b in MIXED:
            sample.het += 1
            sample.dropped.add(p)
        elif b == "-":
            gaps += 1
            sample.dropped.add(p)
        else:
            sample.nocall += 1
    deleted = gaps
    if covered:
        for p in range(min(covered), max(covered) + 1):
            if p not in covered:
                deleted += 1
                sample.dropped.add(p)
    sample.indel = deleted
    sample.called = len(sample.by_pos)
    sample.rows = len(covered)
    return {"length": len(seq), "covered": len(covered) - gaps, "deleted": deleted,
            "ambiguous": sample.het, "unknown": sample.nocall,
            "inserted": sum(1 for i in mapping if i < 0)}


def resolve(sample, db, args):
    """The sample's calls in rCRS coordinates, with the coordinate system and how gaps were filled."""
    info = {"filled": 0, "background": None}
    if sample.kind == "fasta":
        if sample.sequence_info is None:
            sample.sequence_info = align_sequence(sample, db)
        info["sequence"] = sample.sequence_info
        return "aligned", dict(sample.by_pos), info
    mode = "rCRS" if sample.kind in ("hsd", "list") else choose_coordinates(sample, db, args.coordinates)
    if mode == "hg19":
        pmap = db.hg19_map()
        refseq = db.hg19

        def conv(p):
            return pmap[p] if 0 < p < len(pmap) else 0
    else:
        refseq = db.rcrs

        def conv(p):
            return p if 0 < p <= MT_LENGTH else 0
    calls = {}
    for p, b in sample.by_pos.items():
        q = conv(p)
        if q:
            calls[q] = b
    dropped = {conv(p) for p in sample.dropped}
    blocked = {conv(p) for p in sample.blocked}
    for start, end in sample.ref_blocks:
        for p in range(start, min(end, len(refseq)) + 1):
            q = conv(p)
            if q and q not in calls and q not in blocked and refseq[p - 1] in BASES:
                calls[q] = refseq[p - 1]
    background = "rCRS" if mode == "rCRS" else "hg19 chrM"
    if sample.kind in ("hsd", "list"):
        # Lists written against the RSRS (as FamilyTreeDNA can show them) name RSRS alleles as the starting allele.
        votes = 0
        for pos, before, base in sample.from_alleles:
            rsrs, rcrs = db.root_allele(pos), db.rcrs[pos - 1]
            if rsrs == rcrs:
                continue
            if before == rsrs or base == rcrs:
                votes += 1
            elif before == rcrs or base == rsrs:
                votes -= 1
        if votes > 0:
            background = "RSRS"
        for pos, before, base in sample.from_alleles:
            if base is None and pos not in dropped:
                allele = db.root_allele(pos) if background == "RSRS" else db.rcrs[pos - 1]
                if allele in TRANSITION:
                    calls[pos] = TRANSITION[allele]
    fill = sample.fill if args.unlisted == "auto" else args.unlisted == "reference"
    if fill:
        if mode == "hg19":
            source = {}
            for p in range(1, len(refseq) + 1):
                q = conv(p)
                if q:
                    source[q] = refseq[p - 1]
        for q in db.site_markers:
            if q in calls or q in blocked or q in dropped:
                continue
            if not any(a <= q <= b for a, b in sample.fill_ranges):
                continue
            if background == "RSRS":
                base = db.root_allele(q)
            elif mode == "hg19":
                base = source.get(q)
            else:
                base = db.rcrs[q - 1]
            if base in BASES:
                calls[q] = base
                info["filled"] += 1
        info["background"] = background
    for q in dropped:
        calls.pop(q, None)
    calls.pop(0, None)
    return mode, calls, info


def log_odds(error_rate):
    return math.log((1.0 - error_rate) / error_rate)


def site_weight(db, pos, args, rate, cache):
    n = db.recurrence.get(pos, 1)
    if n not in cache:
        e = min(args.max_error_rate, args.error_rate + rate * max(n - 1, 0))
        cache[n] = log_odds(max(e, args.error_rate))
    return cache[n]


def classify(calls, db, args, rate):
    direct = possible_flips = 0
    for pos, c in calls.items():
        if pos in db.site_markers:
            alleles = db.alleles(pos)
            if c in alleles:
                direct += 1
            elif COMPLEMENT.get(c) in alleles and not all(COMPLEMENT[a] in alleles for a in alleles):
                possible_flips += 1
    use_complement = args.complement == "yes" or (
        args.complement == "auto" and possible_flips >= 5 and possible_flips >= 0.2 * (direct + possible_flips))
    obs = {}
    private = []
    other = flipped = ambiguous = 0
    cache = {}
    for pos in sorted(calls):
        c = calls[pos]
        if pos in args.exclude or pos in db.excluded:
            continue
        if pos not in db.site_markers:
            ref = db.rcrs[pos - 1]
            if ref in BASES and c != ref and not (use_complement and c == COMPLEMENT[ref]):
                private.append(f"{ref}{pos}{c}")
            continue
        alleles = db.alleles(pos)
        allele = c
        # With the strand in doubt, a call whose complement is also an allele of the tree there could be
        # read either way (A/T and C/G sites, and many recurrent positions).
        if use_complement and c in alleles and COMPLEMENT[c] in alleles:
            ambiguous += 1
            continue
        if c not in alleles:
            if use_complement and COMPLEMENT.get(c) in alleles:
                allele = COMPLEMENT[c]
                flipped += 1
            else:
                other += 1
                continue
        obs[pos] = (allele, site_weight(db, pos, args, rate, cache))
    return obs, private, other, flipped, ambiguous, use_complement


def place(db, delta, min_support):
    n = db.n
    parent = db.parent
    s = delta[:]
    for i in range(1, n):
        s[i] += s[parent[i]]
    best_in = s[:]
    for i in range(n - 1, 0, -1):
        if best_in[i] > best_in[parent[i]]:
            best_in[parent[i]] = best_in[i]
    neg = float("-inf")
    prefix = [neg] * (n + 1)
    for i in range(n):
        prefix[i + 1] = s[i] if s[i] > prefix[i] else prefix[i]
    suffix = [neg] * (n + 1)
    for i in range(n - 1, -1, -1):
        suffix[i] = s[i] if s[i] > suffix[i + 1] else suffix[i + 1]

    def best_out(i):
        a = prefix[i]
        b = suffix[i + db.size[i]]
        return a if a > b else b

    top = max(s)
    tied = [False] * n
    tied_above = [False] * n
    heads = []
    for i in range(n):
        tied[i] = s[i] >= top - 1e-9
        if i:
            tied_above[i] = tied_above[parent[i]] or tied[parent[i]]
        if tied[i] and not tied_above[i]:
            heads.append(i)
    best = heads[0]
    for h in heads[1:]:
        a, b = best, h
        while db.depth[a] > db.depth[b]:
            a = parent[a]
        while db.depth[b] > db.depth[a]:
            b = parent[b]
        while a != b:
            a, b = parent[a], parent[b]
        best = a

    threshold = math.log(min_support / (1.0 - min_support))
    path = db.path(best)
    margins = []
    for node in path:
        out = best_out(node)
        margins.append(float("inf") if out == neg else best_in[node] - out)
    confident = 0
    for k, margin in enumerate(margins):
        if margin >= threshold:
            confident = k
    return {
        "best": best,
        "heads": heads,
        "path": path,
        "margins": margins,
        "terminal": path[confident],
        "confident_len": confident + 1,
    }


def support_from_margin(margin):
    if margin == float("inf"):
        return 1.0
    if margin > 700:
        return 1.0
    return 1.0 / (1.0 + math.exp(-margin))


def analyse(sample, db, args):
    mode, calls, info = resolve(sample, db, args)
    tree_called = sum(1 for p in calls if p in db.site_markers)
    whole = tree_called >= WHOLE_SEQUENCE * len(db.site_markers)
    rate = args.recurrence_rate
    if rate is None:
        rate = RECURRENCE_RATE_SEQUENCE if whole else RECURRENCE_RATE_ARRAY
    obs, private, other, flipped, ambiguous, use_complement = classify(calls, db, args, rate)
    qc = {
        "mt_rows": sample.rows,
        "mt_called": sample.called,
        "mt_no_call": sample.nocall,
        "mt_heteroplasmic": sample.het,
        "mt_indel": sample.indel,
        "mt_filtered": sample.filtered,
        "mt_conflicting_duplicates": len(sample.conflicting_pos),
        "listed_variants": sample.listed if sample.kind in ("hsd", "list") else None,
        "positions_filled": info["filled"],
        "filled_with": info["background"],
        "sequence": info.get("sequence"),
        "tree_positions_called": tree_called,
        "whole_sequence": whole,
        "informative_positions": len(obs),
        "unexpected_alleles": other,
        "strand_flipped_calls": flipped,
        "strand_ambiguous_skipped": ambiguous,
    }
    warnings = []
    if sample.called and sample.het > 0.05 * (sample.called + sample.het) and sample.het >= 5:
        warnings.append(f"{sample.het} heteroplasmic or mixed calls ({sample.het / (sample.called + sample.het):.0%}); "
                        "possible contamination or a mixed sample")
    if use_complement:
        warnings.append(f"{flipped} calls matched only on the opposite strand and were complemented; "
                        f"{ambiguous} calls were skipped because their strand cannot be told")
    if sample.filter_ignored:
        warnings.append(f"every MT row carries the VCF filter {sample.filter_ignored!r}, so it was read as a label "
                        "and the rows were used")
    if mode == "hg19":
        warnings.append("positions are on the UCSC hg19 chrM sequence (NC_001807) and were converted to the rCRS")
    if info["background"] == "RSRS":
        warnings.append("the variants are listed against the RSRS, so unlisted positions were given the RSRS allele")
    result = {
        "file": sample.path,
        "vendor": sample.vendor,
        "input": sample.kind,
        "sample": sample.name,
        "coordinates": mode,
        "tree": db.version,
        "parameters": {"error_rate": args.error_rate, "recurrence_rate": rate,
                       "max_error_rate": args.max_error_rate, "min_support": args.min_support},
        "qc": qc,
        "warnings": warnings,
        "private_mutations": private,
    }
    if not obs:
        if sample.kind in ("table", "vcf") and sample.rows == 0 and not sample.ref_blocks:
            reason = "the file has no mitochondrial (MT) rows"
        elif sample.kind == "fasta" and not calls:
            reason = "the sequence could not be aligned to the rCRS"
        elif not calls:
            reason = "no mtDNA position has a usable call"
        elif sample.rows and sample.called < 0.1 * sample.rows:
            reason = "almost all mtDNA calls are missing"
        else:
            reason = "no mtDNA call matched a position used by the tree"
        result.update({"status": "no_result", "reason": reason})
        return result

    delta = [0.0] * db.n
    for pos, (c, w) in obs.items():
        if db.root_allele(pos) != c:
            delta[0] -= w
        for m in db.site_markers[pos]:
            after = 0.0 if m.to == c or m.to == "?" else -w
            before = 0.0 if m.frm == c or m.frm == "?" else -w
            delta[m.node] += after - before
    fit = place(db, delta, args.min_support)
    best = fit["best"]
    terminal = fit["terminal"]
    if terminal == 0:
        p = support_from_margin(fit["margins"][-1])
        if best == 0:
            reason = f"the calls match the root of the tree ({db.ids[0]}, the RSRS) better than any branch below it"
        else:
            reason = (f"the evidence is too weak to place the sample (best branch {db.ids[best]} "
                      f"at {fmt_support(p)} support)")
        result.update({"status": "no_result", "reason": reason})
        return result

    # A mutation undone further down the same path cannot be seen in the sample; only the last change
    # at each position on the best path is scored as found or missing there. Below the reported
    # branch every mutation counts towards its subclades.
    on_path = set(fit["path"])
    low, high = terminal, terminal + db.size[terminal]
    last_on_path = {}
    node_obs = {}
    for pos, (c, w) in obs.items():
        markers = db.site_markers[pos]
        last = None
        for m in markers:
            if m.node in on_path and (last is None or db.depth[m.node] >= db.depth[last.node]):
                last = m
        last_on_path[pos] = last
        for m in markers:
            if m.to != "?" and (m is last or (low < m.node < high and m.node not in on_path)):
                node_obs.setdefault(m.node, []).append((m, c, c == m.to))

    def describe(item):
        m, c, found = item
        return {"mutation": m.name, "branch": db.ids[m.node], "position": m.pos, "before": m.frm, "after": m.to,
                "call": c, "state": "found" if found else "missing", "recurrence": db.recurrence.get(m.pos, 0)}

    path_rows = []
    for k, node in enumerate(fit["path"]):
        items = sorted(node_obs.get(node, []), key=lambda o: o[0].pos)
        path_rows.append({
            "id": db.ids[node],
            "found": sum(1 for o in items if o[2]),
            "missing": sum(1 for o in items if not o[2]),
            "support": support_from_margin(fit["margins"][k]),
            "confident": k < fit["confident_len"],
            "formed_ybp": db.formed[node] if db.formed[node] > 0 else None,
            "tmrca_ybp": db.tmrca[node] if db.tmrca[node] > 0 else None,
            "mutations": [describe(o) for o in items],
        })

    path_rank = {node: k for k, node in enumerate(fit["path"])}
    missing = []
    extra = []
    unresolved_below = []
    for pos in sorted(obs):
        c = obs[pos][0]
        last = last_on_path[pos]
        expected = last.to if last else db.root_allele(pos)
        if expected in (c, "?"):
            continue
        if last is not None:
            missing.append({"mutation": last.name, "branch": db.ids[last.node], "position": pos, "call": c,
                            "recurrence": db.recurrence.get(pos, 0), "rank": path_rank[last.node]})
            continue
        seen = [m for m in db.site_markers[pos] if m.to == c and m.node not in on_path]
        entry = {"mutation": f"{expected}{pos}{c}", "position": pos, "call": c,
                 "recurrence": db.recurrence.get(pos, 0),
                 "elsewhere": [db.ids[m.node] for m in seen[:12]], "elsewhere_count": len(seen)}
        if any(db.contains(best, m.node) for m in seen):
            unresolved_below.append(entry)
        else:
            extra.append(entry)
    missing.sort(key=lambda c: c.pop("rank"))

    sub_d = [0] * db.n
    sub_a = [0] * db.n
    for node, items in node_obs.items():
        for o in items:
            if o[2]:
                sub_d[node] += 1
            else:
                sub_a[node] += 1
    for i in range(high - 1, low, -1):
        sub_d[db.parent[i]] += sub_d[i]
        sub_a[db.parent[i]] += sub_a[i]
    subclades = []
    untested = 0
    for child in db.children(terminal):
        own = sorted(node_obs.get(child, []), key=lambda o: o[0].pos)
        own_d = sum(1 for o in own if o[2])
        own_a = len(own) - own_d
        if not sub_d[child] and not sub_a[child]:
            untested += 1
            continue
        if sub_d[child]:
            status = "found_unconfirmed"
        elif own_a:
            status = "missing"
        else:
            status = "downstream_missing"
        downstream = []
        if status == "downstream_missing":
            stack = [child]
            while stack and len(downstream) < 6:
                x = stack.pop()
                for o in node_obs.get(x, []):
                    if not o[2] and o[0].name not in downstream:
                        downstream.append(o[0].name)
                stack.extend(db.children(x))
        subclades.append({
            "id": db.ids[child],
            "status": status,
            "found": own_d,
            "missing": own_a,
            "subtree_found": sub_d[child],
            "subtree_missing": sub_a[child],
            "mutations": [o[0].name + ("+" if o[2] else "-") for o in own][:6],
            "downstream_mutations": downstream[:6],
        })
    order = {"found_unconfirmed": 0, "missing": 1, "downstream_missing": 2}
    subclades.sort(key=lambda s: (order[s["status"]], -s["subtree_missing"] - s["subtree_found"]))

    margin = fit["margins"][fit["confident_len"] - 1]
    result.update({
        "status": "ok",
        "haplogroup": db.ids[terminal],
        "major": db.major(terminal),
        "support": support_from_margin(margin),
        "margin_log_odds": None if margin == float("inf") else round(margin, 3),
        "formed_ybp": db.formed[terminal] if db.formed[terminal] > 0 else None,
        "tmrca_ybp": db.tmrca[terminal] if db.tmrca[terminal] > 0 else None,
        "best_scoring_branch": db.ids[best],
        "ties": [db.ids[h] for h in fit["heads"]] if len(fit["heads"]) > 1 else [],
        "path": path_rows,
        "conflicts": {"missing_on_path": missing, "extra_off_path": extra},
        "unresolved_below": unresolved_below,
        "subclades": subclades,
        "subclades_untested": untested,
    })
    return result


def fmt_int(n):
    return f"{n:,}"


def plural(n, one, many):
    return f"{n:,} {one if n == 1 else many}"


def fmt_support(p):
    if p >= 0.9999:
        return ">99.99%"
    return f"{p * 100:.2f}%"


def recurs(c):
    return f" [mutates {c['recurrence']}x in the tree]" if c["recurrence"] > 1 else ""


def render(result, style, verbose):
    out = []
    add = out.append
    add(style.bold(result["file"]))
    qc = result["qc"]
    kind = result["input"]
    source = result["vendor"] or {"vcf": "VCF", "fasta": "FASTA", "hsd": "HaploGrep profile",
                                  "list": "variant list"}.get(kind, "unrecognised vendor")
    if result.get("sample"):
        source += f" sample {result['sample']}"
    if kind in ("hsd", "list"):
        add(f"  Source        {source}")
    else:
        add(f"  Source        {source}, {COORDINATE_NAMES.get(result['coordinates'], result['coordinates'])}")
    tail = f"; {fmt_int(qc['informative_positions'])} tree positions informative" \
        + (f", {fmt_int(qc['unexpected_alleles'])} with unexpected alleles" if qc["unexpected_alleles"] else "")
    if kind == "fasta" and qc["sequence"]:
        seq = qc["sequence"]
        extras = [f"{fmt_int(seq['deleted'])} deleted" if seq["deleted"] else "",
                  f"{fmt_int(seq['ambiguous'])} ambiguous" if seq["ambiguous"] else "",
                  f"{fmt_int(seq['unknown'])} N" if seq["unknown"] else ""]
        add(f"  Sequence      {fmt_int(seq['length'])} bp covering {fmt_int(seq['covered'])} rCRS positions"
            + "".join(", " + e for e in extras if e) + tail)
    elif kind in ("hsd", "list"):
        add(f"  Variants      {fmt_int(qc['listed_variants'])} listed, other positions taken as "
            f"{qc['filled_with'] or 'unknown'}" + tail)
    else:
        line = (f"  MT calls      {fmt_int(qc['mt_called'])} of {fmt_int(qc['mt_rows'])} rows called"
                + (f", {fmt_int(qc['mt_heteroplasmic'])} heteroplasmic" if qc["mt_heteroplasmic"] else "")
                + (f", {fmt_int(qc['mt_filtered'])} filtered" if qc["mt_filtered"] else ""))
        if qc["filled_with"]:
            line += f"; unlisted positions taken as {qc['filled_with']}"
        add(line + tail)
    for w in result.get("warnings", []):
        add(f"  Warning       {w}")
    if result["status"] != "ok":
        add(f"  Result        {style('no mtDNA haplogroup', '31')}: {result['reason']}")
        return "\n".join(out)

    support = result["support"]
    add(f"  Haplogroup    {style.bold(result['haplogroup'])}  (major clade {result['major']})")
    add(f"  Support       {style.support(fmt_support(support), support)}")
    ages = []
    if result["formed_ybp"] is not None:
        ages.append(f"formed {fmt_int(result['formed_ybp'])} ybp")
    if result["tmrca_ybp"] is not None:
        ages.append(f"TMRCA {fmt_int(result['tmrca_ybp'])} ybp")
    if ages:
        add(f"  YFull age     {', '.join(ages)}")
    if result["ties"]:
        add(f"  Ambiguous     equally likely branches: {', '.join(result['ties'])}")

    rows = result["path"]
    start = 0
    if not verbose:
        ids = [r["id"] for r in rows]
        if result["major"] in ids:
            start = ids.index(result["major"])
    head, tail_rows = rows[:start], rows[start:]
    shown = [r for r in tail_rows if verbose or r["found"] or r["missing"] or r["id"] == result["haplogroup"]]
    width = max([len(r["id"]) + 2 for r in shown] + [12]) + 2
    add("")
    add(style.dim(f"  {'branch':<{width}}{'found':>6}{'missing':>9}  {'support':>8}  mutations"))
    if head:
        d = sum(r["found"] for r in head)
        a = sum(r["missing"] for r in head)
        p = min(r["support"] for r in head)
        add(f"  {head[0]['id'] + '..' + head[-1]['id']:<{width}}{d:>6}{a:>9}  {fmt_support(p):>8}  "
            f"{plural(len(head), 'branch', 'branches')} above {tail_rows[0]['id'] if tail_rows else ''}")
    for r in shown:
        names = [x["mutation"] for x in r["mutations"] if x["state"] == "found"][:5]
        neg = [x["mutation"] for x in r["mutations"] if x["state"] == "missing"][:3]
        text = ", ".join(names) + ("; " if names and neg else "") + ("missing " + ", ".join(neg) if neg else "")
        label = r["id"] + ("" if r["confident"] else " ?")
        line = f"  {label:<{width}}{r['found']:>6}{r['missing']:>9}  {fmt_support(r['support']):>8}  {text}"
        add(line if r["confident"] else style.dim(line))
    hidden = len(tail_rows) - len(shown)
    if hidden:
        add(style.dim(f"  ({plural(hidden, 'branch', 'branches')} on this path without positions in the file; -v lists them)"))
    if any(not r["confident"] for r in rows):
        add(style.dim(f"  ? = below the {result['parameters']['min_support']:.0%} support threshold, not reported"))

    subs = result["subclades"]
    if subs or result["subclades_untested"]:
        add("")
        add(f"  Subclades of {result['haplogroup']}")
        limit = None if verbose else 8
        for s in subs[:limit]:
            if s["status"] == "found_unconfirmed":
                text = (f"{s['subtree_found']} found, {s['subtree_missing']} missing in this clade, "
                        "not enough to report")
            elif s["status"] == "missing":
                text = "missing: " + ", ".join(m.rstrip("-") for m in s["mutations"] if m.endswith("-"))
            else:
                text = "not in the file; downstream mutations missing: " + ", ".join(s["downstream_mutations"])
            add(f"    {s['id']:<{max(12, width - 2)}}{text}")
        if limit and len(subs) > limit:
            add(style.dim(f"    ... {plural(len(subs) - limit, 'more tested subclade', 'more tested subclades')} (-v lists them)"))
        if result["subclades_untested"]:
            add(style.dim(f"    {plural(result['subclades_untested'], 'subclade', 'subclades')} without positions in this file"))

    conflicts = result["conflicts"]
    n_conf = len(conflicts["missing_on_path"]) + len(conflicts["extra_off_path"])
    if n_conf:
        add("")
        add(f"  Calls that disagree with this path: {n_conf}")
        limit = None if verbose else 6
        for c in conflicts["missing_on_path"][:limit]:
            add(f"    {c['mutation']:<12} missing (call {c['call']}) at {c['branch']}, which is on the path" + recurs(c))
        for c in conflicts["extra_off_path"][:limit]:
            where = (f"also at {', '.join(c['elsewhere'][:3])}"
                     + (f" and {c['elsewhere_count'] - 3} more branches" if c["elsewhere_count"] > 3 else "")
                     if c["elsewhere_count"] else "not on any branch of the tree")
            add(f"    {c['mutation']:<12} extra (call {c['call']}), {where}" + recurs(c))
        rest = n_conf - len(conflicts["missing_on_path"][:limit]) - len(conflicts["extra_off_path"][:limit])
        if rest > 0:
            add(style.dim(f"    ... {rest} more (-v or --json lists all)"))
    private = result["private_mutations"]
    if private:
        add("")
        limit = None if verbose else 12
        add(f"  Private mutations (positions the tree does not use): {', '.join(private[:limit])}"
            + (f" ... {len(private) - limit} more" if limit and len(private) > limit else ""))
    return "\n".join(out)


def summary_line(result):
    if result["status"] != "ok":
        return "\t".join([result["file"], "-", "-", "-", str(result["qc"]["informative_positions"]), result["reason"]])
    return "\t".join([result["file"], result["haplogroup"], result["major"], f"{result['support']:.6f}",
                      str(result["qc"]["informative_positions"]), result["coordinates"]])


def snp_report(db, queries, samples, calls, style):
    lines = []
    for query in queries:
        mut = parse_mutation(query)
        if mut is None or mut[0] not in ("sub", "het", "nocall"):
            lines.append(f"{query}: not a position or substitution")
            continue
        pos = mut[1]
        markers = db.site_markers.get(pos, [])
        rcrs, rsrs = db.rcrs[pos - 1], db.root_allele(pos)
        head = f"{style.bold(str(pos))}  rCRS {rcrs}, RSRS {rsrs}"
        if not markers:
            lines.append(head + "  (not used by the tree)")
        else:
            lines.append(head + f"  {plural(db.recurrence.get(pos, 0), 'mutation', 'mutations')} in the tree")
            groups = {}
            for m in markers:
                groups.setdefault(m.name, []).append(m.node)
            for name, nodes in groups.items():
                if mut[3] and mut[3] in BASES and not name.rstrip("!").endswith(mut[3]):
                    continue
                listed = ", ".join(f"{db.ids[n]} ({db.major(n)})" for n in nodes[:6])
                lines.append(f"    {name:<10} at {listed}" + (f" and {len(nodes) - 6} more" if len(nodes) > 6 else ""))
        for s, c in zip(samples, calls):
            call = c.get(pos)
            if call is None:
                state = "not in file or no call"
            elif call == rcrs:
                state = f"{call} (rCRS allele)"
            else:
                state = f"{call} ({rcrs}{pos}{call})"
            lines.append(f"    {s.label}: {state}")
    return "\n".join(lines)


def node_report(db, query, style):
    idx = db.index_of(query)
    if idx is None:
        idx = db.index_of(re.split(r"[+\s(]", query, maxsplit=1)[0])
    if idx is None:
        return f"{query}: no branch with that name"
    lines = [style.bold(db.ids[idx]) + f"  (major clade {db.major(idx)})"]
    ages = []
    if db.formed[idx] > 0:
        ages.append(f"formed {fmt_int(db.formed[idx])} ybp")
    if db.tmrca[idx] > 0:
        ages.append(f"TMRCA {fmt_int(db.tmrca[idx])} ybp")
    if ages:
        lines.append("  " + ", ".join(ages))
    lines.append("  path: " + " > ".join(db.ids[i] for i in db.path(idx)))
    own = sorted((m for ms in db.site_markers.values() for m in ms if m.node == idx), key=lambda m: m.pos)
    if own:
        lines.append("  mutations: " + ", ".join(m.name for m in own))
    lines.append("  differences from the rCRS: " + (" ".join(db.motif(idx)) or "none"))
    kids = db.children(idx)
    if kids:
        lines.append(f"  {len(kids)} direct subclades: " + ", ".join(db.ids[k] for k in kids[:40])
                     + (" ..." if len(kids) > 40 else ""))
    lines.append(f"  {fmt_int(db.size[idx] - 1)} branches below")
    return "\n".join(lines)


def clean_path(text):
    text = text.strip()
    if len(text) >= 2 and text[0] == text[-1] and text[0] in "'\"":
        text = text[1:-1]
    return os.path.expanduser(text.replace("\\ ", " "))


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Predict an mtDNA haplogroup from a raw DNA file (23andMe, AncestryDNA, FTDNA, "
                    "MyHeritage, LivingDNA, VCF, FASTA, HaploGrep, ...), offline.")
    ap.add_argument("files", nargs="*", help="raw data files (.txt/.csv/.vcf/.fasta/.hsd, optionally .gz/.bz2/.zip)")
    ap.add_argument("--db", default=DEFAULT_DB, help="tree database (default: mtdb.tsv.gz next to this script)")
    ap.add_argument("--coordinates", choices=["auto", "rCRS", "hg19"], default="auto",
                    help="numbering of the file's MT positions (default: detected from the data)")
    ap.add_argument("--unlisted", choices=["auto", "reference", "unknown"], default="auto",
                    help="positions a VCF or variant list leaves out: reference allele or unknown "
                         "(default: reference for variant-only files)")
    ap.add_argument("--error-rate", type=float, default=0.01,
                    help="per-call error rate at positions that mutate once in the tree (default 0.01)")
    ap.add_argument("--recurrence-rate", type=float,
                    help="added to the error rate for each further time a position mutates in the tree "
                         f"(default {RECURRENCE_RATE_SEQUENCE:g} for whole sequences, {RECURRENCE_RATE_ARRAY:g} otherwise)")
    ap.add_argument("--max-error-rate", type=float, default=0.4,
                    help="error rate ceiling for the most recurrent positions (default 0.4)")
    ap.add_argument("--min-support", type=float, default=0.95,
                    help="clade support required to report a branch (default 0.95)")
    ap.add_argument("--complement", choices=["auto", "yes", "no"], default="auto",
                    help="accept reverse-strand calls (default: only when the file shows a strand problem)")
    ap.add_argument("--exclude", default="", help="comma-separated positions to ignore (16189,152)")
    ap.add_argument("--sample", help="sample to read from a multi-sample VCF, FASTA or HSD file")
    ap.add_argument("--snp", default="", help="show the tree and each file's call at these positions (16519,T152C)")
    ap.add_argument("--node", help="print a haplogroup with its path, mutations and subclades")
    ap.add_argument("--json", action="store_true", help="write JSON instead of text")
    ap.add_argument("--summary", action="store_true", help="one tab-separated line per file")
    ap.add_argument("-v", "--verbose", action="store_true", help="list every branch and conflict")
    ap.add_argument("--no-color", action="store_true")
    ap.add_argument("--version", action="version", version=f"%(prog)s {__version__}")
    args = ap.parse_args(argv)

    for name, value in (("--error-rate", args.error_rate), ("--max-error-rate", args.max_error_rate),
                        ("--min-support", args.min_support)):
        if not 0.0 < value < 1.0:
            ap.error(f"{name} must be between 0 and 1")
    if args.recurrence_rate is not None and not 0.0 <= args.recurrence_rate < 1.0:
        ap.error("--recurrence-rate must be between 0 and 1")
    exclude = set()
    for word in re.split(r"[\s,]+", args.exclude):
        mut = parse_mutation(word) if word else None
        if word and mut is None:
            ap.error(f"--exclude: {word} is not an mtDNA position")
        if mut:
            exclude.update(range(mut[1], mut[2] + 1))
    args.exclude = exclude
    queries = [s.strip() for s in re.split(r"[\s,]+", args.snp) if s.strip()]
    color = sys.stdout.isatty() and not args.no_color and "NO_COLOR" not in os.environ and not args.json
    if color and os.name == "nt":
        os.system("")
    style = Style(color)

    files = [clean_path(f) for f in args.files]
    if not files and not args.node and not queries:
        try:
            entered = input("Path to raw DNA file: ")
        except EOFError:
            return 1
        files = [clean_path(entered)] if entered.strip() else []
        if not files:
            return 1

    samples = []
    failures = []
    for path in files:
        if not os.path.isfile(path):
            failures.append({"file": path, "status": "error", "reason": "file not found"})
            continue
        try:
            samples.append(read_sample(path, args.sample))
        except (OSError, ValueError, zipfile.BadZipFile, EOFError) as e:
            failures.append({"file": path, "status": "error", "reason": str(e)})

    try:
        db = TreeDB(args.db)
    except (OSError, ValueError, KeyError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2

    if args.node:
        print(node_report(db, args.node, style))
        if not files:
            return 0
        print()
    if queries:
        resolved = [resolve(s, db, args)[1] for s in samples]
        print(snp_report(db, queries, samples, resolved, style))
        if not samples:
            return 0
        print()

    results = [analyse(s, db, args) for s in samples]
    results.extend(failures)
    if args.json:
        print(json.dumps(results if len(results) != 1 else results[0], indent=1))
    elif args.summary:
        print("file\thaplogroup\tmajor\tsupport\tinformative_positions\tcoordinates")
        for r in results:
            if r["status"] == "error":
                print(f"{r['file']}\t-\t-\t-\t0\terror: {r['reason']}")
            else:
                print(summary_line(r))
    else:
        for i, r in enumerate(results):
            if i:
                print()
            if r["status"] == "error":
                print(f"{style.bold(r['file'])}\n  error: {r['reason']}")
            else:
                print(render(r, style, args.verbose))
        if results and all(r["status"] == "ok" for r in results):
            print()
            print(style.dim(f"  Tree: {db.version}. Support = L(in) / (L(in) + L(out)) for the best placement "
                            f"inside vs outside each clade, at a {args.error_rate * 100:g}% per-call error rate "
                            "that rises at recurrent positions."))
    return 0 if results and all(r["status"] == "ok" for r in results) else 1


if __name__ == "__main__":
    sys.exit(main())
