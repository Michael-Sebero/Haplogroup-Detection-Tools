#!/usr/bin/env python3
"""
Mitochondrial DNA haplogroup predictor for consumer raw DNA files.

Reads 23andMe, AncestryDNA, FamilyTreeDNA, MyHeritage, LivingDNA, tellmeGen,
Genes for Good, Illumina GSA reports, VCF, FASTA and HaploGrep (.hsd) files
(plain, .gz, .bz2 or .zip) and places the sample on the YFull mtDNA tree.
Runs offline.

Method
  The tree is rooted at the RSRS. The allele expected at a position on a
  branch is the root allele, changed by every mutation on the path from the
  root to that branch, back mutations included. For a candidate haplogroup h,
  each call that differs from the allele expected under h costs
  log((1 - e) / e). The error rate e depends on how often the position mutates
  in the tree: --error-rate for a position that mutates once, plus
  --recurrence-rate for every further occurrence, up to --max-error-rate.
  Clade support is L(in) / (L(in) + L(out)), where L(in) and L(out) are the
  likelihoods of the best placements inside and outside the clade. The
  reported haplogroup is the deepest branch on the best path whose support
  reaches --min-support.

Data
  mtdb.tsv.gz, generated by build-mtdb.py:
    tree       YFull MTree (github.com/YFullTeam/MTree), CC BY 4.0
    reference  rCRS (NC_012920.1) and UCSC hg19 chrM (NC_001807.4), NCBI
"""

