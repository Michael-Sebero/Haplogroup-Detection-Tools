#!/usr/bin/env python3
"""
Self-contained checks for y-haplogroup-predictor.py.

Simulates array-like samples from the tree database (every call follows the
path to a random target branch), writes them in each supported vendor format
and checks the placements. Needs only ydb.tsv.gz.
"""

import bz2
import gzip
import importlib.util
import json
import os
import random
import subprocess
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SCRIPT = os.path.join(ROOT, "y-haplogroup-predictor.py")
DB = os.path.join(ROOT, "ydb.tsv.gz")

spec = importlib.util.spec_from_file_location("yhp", SCRIPT)
yhp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(yhp)

COMP = {"A": "T", "C": "G", "G": "C", "T": "A"}
results = []


def check(name, ok, detail=""):
    results.append(ok)
    print(f"{'PASS' if ok else 'FAIL'}  {name}" + (f"  ({detail})" if detail else ""))


def load_all_markers():
    parent, ids, markers = [], [], []
    with gzip.open(DB, "rt") as f:
        for line in f:
            if line[0] == "#":
                continue
            p = line.rstrip("\n").split("\t")
            if p[0] == "N":
                parent.append(int(p[2]))
                ids.append(p[3])
            elif "u" not in p[6]:
                off = int(p[2]) if p[2] else None
                markers.append((int(p[0]), int(p[1]), off, p[3][0], p[3][1], p[4].split("/")[0], p[5]))
    return parent, ids, markers


def simulate(parent, target, panel, error=0.0, rng=random):
    on_path = set()
    x = target
    while x >= 0:
        on_path.add(x)
        x = parent[x]
    calls = {}
    for node, pos, off, anc, der, name, rs in panel:
        allele = der if node in on_path else anc
        if error and rng.random() < error:
            allele = rng.choice([b for b in "ACGT" if b != allele])
        calls[pos] = (allele, off, rs.split(",")[0] if rs else f"i{pos}")
    return calls


def placement_tests(parent, ids, markers):
    rng = random.Random(20260929)
    sites = {}
    for m in markers:
        sites.setdefault(m[1], []).append(m)
    unique = [ms[0] for ms in sites.values() if len(ms) == 1]
    panel = rng.sample(unique, 4000)
    panel_nodes = {m[0] for m in panel}
    depth = [0] * len(parent)
    for i in range(1, len(parent)):
        depth[i] = depth[parent[i]] + 1
    targets = [i for i in range(len(parent)) if i in panel_nodes and depth[i] >= 8]
    targets = rng.sample(targets, 150)
    want = {m[1] for m in panel}
    db = yhp.TreeDB(DB, want)

    class Args:
        error_rate = 0.01
        recurrent_error_rate = 0.1
        min_support = 0.95
        build = "auto"
        complement = "auto"
        exclude = set()

    for error, allowed in ((0.0, 0), (0.01, 3), (0.03, 8)):
        bad = []
        exact = 0
        for t in targets:
            s = yhp.Sample(f"sim_{ids[t]}")
            for pos, (allele, off, rid) in simulate(parent, t, panel, error, rng).items():
                s.add("Y", pos, rid, allele, "call")
            r = yhp.analyse(s, db, Args)
            if r["status"] != "ok":
                bad.append((ids[t], r["reason"]))
                continue
            got = db.index_of(r["haplogroup"])
            if not db.contains(got, t):
                bad.append((ids[t], r["haplogroup"]))
            exact += got == t
        check(f"placement, 150 simulated samples, {error:.0%} genotype errors",
              len(bad) <= allowed, f"{150 - len(bad)} on the true lineage, {exact} exact, first misses {bad[:2]}")
    return panel, targets


def format_tests(parent, ids, panel, target):
    calls = simulate(parent, target, panel)
    tmp = tempfile.mkdtemp(prefix="yhp-test-")
    order = sorted(calls)

    def lines(fmt, calls=calls, pos_of=lambda p, off: p):
        return "".join(fmt(calls[p][2], pos_of(p, calls[p][1]), calls[p][0]) + "\n" for p in order)

    def write(name, text, binary=False):
        path = os.path.join(tmp, name)
        with open(path, "wb" if binary else "w", newline="" if not binary else None) as f:
            f.write(text)
        return path

    h23 = "# This data file generated by 23andMe\n# reference human assembly build 37\n# rsid\tchromosome\tposition\tgenotype\n"
    body23 = lines(lambda r, p, a: f"{r}\tY\t{p}\t{a}")
    files = {
        "23andMe": write("23andme.txt", h23 + body23),
        "23andMe .zip": None,
        "23andMe .gz": write("23andme.txt.gz", gzip.compress((h23 + body23).encode()), True),
        "23andMe .bz2": write("23andme.txt.bz2", bz2.compress((h23 + body23).encode()), True),
        "23andMe CRLF + BOM": write("crlf.txt", "﻿" + (h23 + body23).replace("\n", "\r\n")),
        "AncestryDNA": write("ancestry.txt", "#AncestryDNA raw data download\nrsid\tchromosome\tposition\tallele1\tallele2\n"
                             + lines(lambda r, p, a: f"{r}\t24\t{p}\t{a}\t{a}")),
        "FamilyTreeDNA / MyHeritage CSV": write("myheritage.csv", "# MyHeritage\nRSID,CHROMOSOME,POSITION,RESULT\n"
                                                + lines(lambda r, p, a: f'"{r}","Y","{p}","{a}{a}"')),
        "FTDNA famfinder": write("famfinder.csv", "# famfinder\n# name,chromosome,position,allele1,allele2\n"
                                 + lines(lambda r, p, a: f"{r},Y,{p},{a},{a}")),
        "Illumina GSA report": write("gsa.txt", "[Header]\nGSGT Version\t2.0.4\n[Data]\n"
                                     "Sample Name\tSNP Name\tChr\tPosition\tAllele1 - Forward\tAllele2 - Forward\n"
                                     + lines(lambda r, p, a: f"1\t{r}\tY\t{p}\t{a}\t{a}")),
        "VCF (GRCh37)": write("sample.vcf", "##fileformat=VCFv4.2\n#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS1\n"
                              + lines(lambda r, p, a: f"Y\t{p}\t{r}\t{a}\t.\t.\tPASS\t.\tGT\t0")),
        "GRCh38 coordinates": write("grch38.txt", "# rsid\tchromosome\tposition\tgenotype\n"
                                    + "".join(f"{calls[p][2]}\tY\t{p + calls[p][1]}\t{calls[p][0]}\n"
                                              for p in order if calls[p][1] is not None)),
        "reverse strand": write("flip.txt", h23 + lines(lambda r, p, a: f"{r}\tY\t{p}\t{COMP[a]}")),
    }
    zpath = os.path.join(tmp, "genome.zip")
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("genome_John_Doe_v5_Full.txt", h23 + body23)
    files["23andMe .zip"] = zpath

    def run(path):
        out = subprocess.run([sys.executable, SCRIPT, "--json", "--db", DB, path], capture_output=True, text=True)
        try:
            return json.loads(out.stdout)
        except json.JSONDecodeError:
            return {"status": "crash", "reason": out.stderr.strip().splitlines()[-1:]}

    reference = run(files["23andMe"])
    check("reference file places", reference.get("status") == "ok", reference.get("haplogroup", reference.get("reason")))
    for name, path in files.items():
        r = run(path)
        same = r.get("status") == "ok" and r.get("major") == reference.get("major")
        if name not in ("GRCh38 coordinates", "reverse strand"):
            same = same and r.get("haplogroup") == reference.get("haplogroup")
        if name == "GRCh38 coordinates":
            same = same and r.get("coordinates") == "GRCh38"
        check(f"format: {name}", same, r.get("haplogroup") or str(r.get("reason")))

    female = write("female.txt", h23 + lines(lambda r, p, a: f"{r}\tY\t{p}\t--"))
    r = run(female)
    check("female file gives no haplogroup", r.get("status") == "no_result" and "female" in r.get("reason", ""), r.get("reason"))
    none = write("autosomal.txt", h23 + "rs1\t1\t1000\tAA\nrs2\t2\t2000\tAG\n")
    r = run(none)
    check("file without Y rows gives no haplogroup", r.get("status") == "no_result", r.get("reason"))


def cli_tests():
    out = subprocess.run([sys.executable, SCRIPT, "--db", DB, "--snp", "M269,rs9786184"], capture_output=True, text=True)
    check("--snp lookup by name and rsID", "R-M269" in out.stdout and "R1b" in out.stdout, out.stdout.splitlines()[0] if out.stdout else out.stderr)
    out = subprocess.run([sys.executable, SCRIPT, "--db", DB, "--node", "L21"], capture_output=True, text=True)
    check("--node lookup", out.stdout.startswith("R-L21"), out.stdout.splitlines()[0] if out.stdout else out.stderr)
    out = subprocess.run([sys.executable, SCRIPT, "--db", DB, "/nonexistent/file.txt"], capture_output=True, text=True)
    check("missing file reported, exit code 1", out.returncode == 1 and "file not found" in out.stdout)


def main():
    if not os.path.exists(DB):
        print(f"FAIL  database missing: {DB}")
        return 1
    parent, ids, markers = load_all_markers()
    panel, targets = placement_tests(parent, ids, markers)
    format_tests(parent, ids, panel, targets[0])
    cli_tests()
    print(f"{sum(results)}/{len(results)} passed")
    return 0 if all(results) else 1


if __name__ == "__main__":
    sys.exit(main())
