#!/usr/bin/env python3
"""
Self-contained checks for mt-haplogroup-predictor.py.

Simulates samples from the tree database (every call follows the path to a
random target branch, back mutations included), writes them in each supported
format and checks the placements. Needs only mtdb.tsv.gz.
"""

import bz2
import gzip
import importlib.util
import json
import os
import random
import subprocess
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SCRIPT = os.path.join(ROOT, "mt-haplogroup-predictor.py")
DB = os.path.join(ROOT, "mtdb.tsv.gz")

spec = importlib.util.spec_from_file_location("mhp", SCRIPT)
mhp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mhp)

COMP = {"A": "T", "C": "G", "G": "C", "T": "A"}
results = []


def check(name, ok, detail=""):
    results.append(ok)
    print(f"{'PASS' if ok else 'FAIL'}  {name}" + (f"  ({detail})" if detail else ""))


class Args:
    error_rate = 0.01
    recurrence_rate = None
    max_error_rate = 0.4
    min_support = 0.95
    coordinates = "auto"
    unlisted = "auto"
    complement = "auto"
    exclude = set()


def node_markers(db):
    out = {}
    for markers in db.site_markers.values():
        for m in markers:
            out.setdefault(m.node, []).append(m)
    return out


def genome(db, by_node, target):
    """Allele at every tree position for a sample sitting exactly on target ('?' = deleted)."""
    state = {pos: db.root_allele(pos) for pos in db.site_markers}
    for node in db.path(target):
        for m in by_node.get(node, ()):
            state[m.pos] = m.to
    return state


def simulate(db, by_node, target, panel, error=0.0, rng=random):
    state = genome(db, by_node, target)
    calls = {}
    for pos in panel:
        allele = state.get(pos, db.rcrs[pos - 1])
        if allele not in "ACGT":
            continue
        if error and rng.random() < error:
            allele = rng.choice([b for b in "ACGT" if b != allele])
        calls[pos] = allele
    return calls


def sequence(db, by_node, target):
    state = genome(db, by_node, target)
    seq = []
    for pos, ref in enumerate(db.rcrs, 1):
        if ref not in "ACGT":
            continue
        allele = state.get(pos, ref)
        if allele != "?":
            seq.append(allele)
        if pos == 315:
            seq.append("C")
    return "".join(seq)


def placement_tests(db, by_node):
    rng = random.Random(20261010)
    sites = sorted(db.site_markers)
    panel = sorted(rng.sample(sites, 2500))
    panel_set = set(panel)
    targets = [i for i in range(db.n) if db.depth[i] >= 6
               and any(m.pos in panel_set and m.to != "?" and db.recurrence[m.pos] <= 3 for m in by_node.get(i, ()))]
    targets = rng.sample(targets, 150)
    for error, allowed in ((0.0, 0), (0.01, 3), (0.03, 8)):
        bad = []
        exact = 0
        for t in targets:
            s = mhp.Sample(f"sim_{db.ids[t]}")
            for pos, allele in simulate(db, by_node, t, panel, error, rng).items():
                s.add(pos, allele, "call")
            r = mhp.analyse(s, db, Args)
            if r["status"] != "ok":
                bad.append((db.ids[t], r["reason"]))
                continue
            got = db.index_of(r["haplogroup"])
            if not db.contains(got, t):
                bad.append((db.ids[t], r["haplogroup"]))
            exact += got == t
        check(f"placement, 150 simulated arrays, {error:.0%} genotype errors",
              len(bad) <= allowed, f"{150 - len(bad)} on the true lineage, {exact} exact, first misses {bad[:2]}")
    return panel, targets


def run(path, *extra):
    out = subprocess.run([sys.executable, SCRIPT, "--json", "--db", DB, *extra, path], capture_output=True, text=True)
    try:
        return json.loads(out.stdout)
    except json.JSONDecodeError:
        return {"status": "crash", "reason": out.stderr.strip().splitlines()[-1:]}


def format_tests(db, by_node, panel, target):
    calls = simulate(db, by_node, target, panel)
    tmp = tempfile.mkdtemp(prefix="mthp-test-")
    order = sorted(calls)

    def lines(fmt):
        return "".join(fmt(f"i{p}", p, calls[p]) + "\n" for p in order)

    def write(name, text, binary=False):
        path = os.path.join(tmp, name)
        with open(path, "wb" if binary else "w", newline="" if not binary else None) as f:
            f.write(text)
        return path

    h23 = "# This data file generated by 23andMe\n# reference human assembly build 37\n# rsid\tchromosome\tposition\tgenotype\n"
    body23 = lines(lambda r, p, a: f"{r}\tMT\t{p}\t{a}")
    files = {
        "23andMe": write("23andme.txt", h23 + body23),
        "23andMe .zip": None,
        "23andMe .gz": write("23andme.txt.gz", gzip.compress((h23 + body23).encode()), True),
        "23andMe .bz2": write("23andme.txt.bz2", bz2.compress((h23 + body23).encode()), True),
        "23andMe CRLF + BOM": write("crlf.txt", "﻿" + (h23 + body23).replace("\n", "\r\n")),
        "AncestryDNA": write("ancestry.txt", "#AncestryDNA raw data download\nrsid\tchromosome\tposition\tallele1\tallele2\n"
                             + lines(lambda r, p, a: f"{r}\t26\t{p}\t{a}\t{a}")),
        "FamilyTreeDNA / MyHeritage CSV": write("myheritage.csv", "# MyHeritage\nRSID,CHROMOSOME,POSITION,RESULT\n"
                                                + lines(lambda r, p, a: f'"{r}","MT","{p}","{a}{a}"')),
        "FTDNA famfinder": write("famfinder.csv", "# famfinder\n# name,chromosome,position,allele1,allele2\n"
                                 + lines(lambda r, p, a: f"{r},MT,{p},{a},{a}")),
        "Illumina GSA report": write("gsa.txt", "[Header]\nGSGT Version\t2.0.4\n[Data]\n"
                                     "Sample Name\tSNP Name\tChr\tPosition\tAllele1 - Forward\tAllele2 - Forward\n"
                                     + lines(lambda r, p, a: f"1\t{r}\tMT\t{p}\t{a}\t{a}")),
        "array VCF": write("array.vcf", "##fileformat=VCFv4.2\n##contig=<ID=MT,length=16569>\n"
                           "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS1\n"
                           + lines(lambda r, p, a: f"MT\t{p}\t{r}\t{db.rcrs[p - 1]}\t{a if a != db.rcrs[p - 1] else '.'}"
                                                   f"\t.\tPASS\t.\tGT\t{0 if a == db.rcrs[p - 1] else 1}")),
        "VCF with a FILTER label on every row": write("labelled.vcf", "##fileformat=VCFv4.2\n"
                                                      "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS1\n"
                                                      + lines(lambda r, p, a: f"MT\t{p}\t{r}\t{db.rcrs[p - 1]}\t"
                                                              f"{a if a != db.rcrs[p - 1] else '.'}\t.\tfa\t.\tGT\t"
                                                              f"{0 if a == db.rcrs[p - 1] else 1}")),
        "reverse strand": write("flip.txt", h23 + lines(lambda r, p, a: f"{r}\tMT\t{p}\t{COMP[a]}")),
    }
    zpath = os.path.join(tmp, "genome.zip")
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("genome_John_Doe_v5_Full.txt", h23 + body23)
    files["23andMe .zip"] = zpath

    reference = run(files["23andMe"])
    check("reference file places", reference.get("status") == "ok", reference.get("haplogroup", reference.get("reason")))
    for name, path in files.items():
        r = run(path)
        same = r.get("status") == "ok" and r.get("major") == reference.get("major")
        if name != "reverse strand":
            same = same and r.get("haplogroup") == reference.get("haplogroup")
        check(f"format: {name}", same, r.get("haplogroup") or str(r.get("reason")))

    nocalls = write("nocalls.txt", h23 + lines(lambda r, p, a: f"{r}\tMT\t{p}\t--"))
    r = run(nocalls)
    check("file of no-calls gives no haplogroup", r.get("status") == "no_result", r.get("reason"))
    none = write("autosomal.txt", h23 + "rs1\t1\t1000\tAA\nrs2\t2\t2000\tAG\n")
    r = run(none)
    check("file without MT rows gives no haplogroup", r.get("status") == "no_result" and "MT" in r.get("reason", ""),
          r.get("reason"))


def sequence_tests(db, by_node, targets):
    rng = random.Random(7)
    tmp = tempfile.mkdtemp(prefix="mthp-seq-")
    picks = rng.sample(targets, 6)
    hg19_to_rcrs = db.hg19_map()
    rcrs_to_hg19 = {q: p for p, q in enumerate(hg19_to_rcrs) if q}
    for t in picks:
        name = db.ids[t]
        state = genome(db, by_node, t)
        seq = sequence(db, by_node, t)
        variants = sorted((p, a) for p, a in state.items() if a in "ACGT" and a != db.rcrs[p - 1])
        deleted = sorted(p for p, a in state.items() if a == "?")
        motif = db.motif(t)
        files = {
            "FASTA": ("seq.fasta", f">{name} simulated\n" + "\n".join(seq[i:i + 70] for i in range(0, len(seq), 70)) + "\n"),
            "variant-only VCF": ("wgs.vcf", "##fileformat=VCFv4.2\n##contig=<ID=chrM,length=16569>\n"
                                 "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS1\n"
                                 + "".join(f"chrM\t{p}\t.\t{db.rcrs[p - 1]}\t{a}\t.\tPASS\t.\tGT\t1/1\n" for p, a in variants)),
            "HaploGrep .hsd": ("profile.hsd", "SampleId\tRange\tHaplogroup\tPolymorphisms\n"
                               f"{name}\t1-16569\t?\t" + "\t".join(motif) + "\n"),
            "variant list against the RSRS": ("rsrs.txt", " ".join(
                f"{db.root_allele(p)}{p}{a}" for p, a in sorted(state.items())
                if a in "ACGT" and a != db.root_allele(p)) + "\n"),
        }
        gvcf = []
        start = 1
        for p, a in variants + [(len(db.rcrs) + 1, None)]:
            if p > start:
                gvcf.append(f"chrM\t{start}\t.\t{db.rcrs[start - 1]}\t<NON_REF>\t.\t.\tEND={p - 1}\tGT\t0/0\n")
            if a:
                gvcf.append(f"chrM\t{p}\t.\t{db.rcrs[p - 1]}\t{a},<NON_REF>\t.\tPASS\t.\tGT:AD\t1/1:0,30,0\n")
            start = p + 1
        files["gVCF"] = ("sample.g.vcf", "##fileformat=VCFv4.2\n#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS1\n"
                         + "".join(gvcf))
        hg19_rows = []
        for p in range(1, len(db.hg19) + 1):
            q = hg19_to_rcrs[p]
            if not q or q in deleted:
                continue
            allele = state.get(q, db.rcrs[q - 1])
            if allele in "ACGT" and allele != db.hg19[p - 1] and q not in db.excluded:
                hg19_rows.append(f"chrM\t{p}\t.\t{db.hg19[p - 1]}\t{allele}\t.\tPASS\t.\tGT\t1\n")
        files["hg19 chrM VCF"] = ("hg19.vcf", "##fileformat=VCFv4.2\n##contig=<ID=chrM,length=16571>\n"
                                  "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS1\n" + "".join(hg19_rows))
        for label, (fname, text) in files.items():
            path = os.path.join(tmp, f"{len(results)}_{fname}")
            with open(path, "w") as f:
                f.write(text)
            r = run(path)
            got = db.index_of(r["haplogroup"]) if r.get("status") == "ok" else None
            ok = got is not None and db.contains(got, t) and db.depth[t] - db.depth[got] <= 1
            check(f"full sequence: {label} for {name}", ok,
                  (r.get("haplogroup") or str(r.get("reason"))) + f", {r.get('coordinates')}")
    return rcrs_to_hg19


def cli_tests():
    out = subprocess.run([sys.executable, SCRIPT, "--db", DB, "--snp", "2706,16519"], capture_output=True, text=True)
    check("--snp lookup", "G2706A" in out.stdout and "not used by the tree" in out.stdout,
          out.stdout.splitlines()[0] if out.stdout else out.stderr)
    out = subprocess.run([sys.executable, SCRIPT, "--db", DB, "--node", "H1"], capture_output=True, text=True)
    check("--node lookup", out.stdout.startswith("H1 ") and "263G 750G 1438G 3010A 4769G 8860G 15326G" in out.stdout,
          out.stdout.splitlines()[0] if out.stdout else out.stderr)
    out = subprocess.run([sys.executable, SCRIPT, "--db", DB, "--node", "H2a2a1"], capture_output=True, text=True)
    check("the rCRS haplogroup has no differences from the rCRS", "differences from the rCRS: none" in out.stdout)
    out = subprocess.run([sys.executable, SCRIPT, "--db", DB, "/nonexistent/file.txt"], capture_output=True, text=True)
    check("missing file reported, exit code 1", out.returncode == 1 and "file not found" in out.stdout)


def main():
    if not os.path.exists(DB):
        print(f"FAIL  database missing: {DB}")
        return 1
    db = mhp.TreeDB(DB)
    by_node = node_markers(db)
    panel, targets = placement_tests(db, by_node)
    format_tests(db, by_node, panel, targets[0])
    sequence_tests(db, by_node, targets)
    cli_tests()
    print(f"{sum(results)}/{len(results)} passed")
    return 0 if all(results) else 1


if __name__ == "__main__":
    sys.exit(main())
